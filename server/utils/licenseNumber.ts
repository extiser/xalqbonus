/**
 * Нормализация номера водительского удостоверения.
 *
 * Номер ВУ — признак человека, а не учётки: именно им склеиваются четыре пары двойников
 * из двенадцати, которых не ловит `profile_id` (docs/drivers.md). Поэтому приведение
 * к каноническому виду — часть ядра, а не деталь импорта.
 *
 * Поле `normalized_number` из Fleet API не используется: оно побайтово равно `number`
 * у всех 25 390 профилей реестра — «normalized» в имени поля обещание, а не факт.
 */

/**
 * Кириллица → латиница, транслитерацией.
 *
 * Таблица собрана по данным, а не по начертанию букв. В реестре 178 номеров с кириллицей
 * и в старой базе 16, и встречаются в них только `Г Л Ж Б Д Я Ц П Ю Щ Ф З Э` — то есть
 * ровно те буквы, у которых латинского двойника по виду НЕТ. Омоглифных `А В Е К М Н О
 * Р С Т У Х` нет ни одной: таблица похожих начертаний на этих данных не сработала бы
 * ни разу. Соответствие подтверждается парами серий из самого реестра: `AФ` ↔ `AF`,
 * `AГЛ` ↔ `AGL`, `AГT` ↔ `AGT`, `AГБ` ↔ `AGB`, `AAБ` ↔ `AAB` — номер писали переводом
 * букв, а не подбором похожих.
 *
 * Пять букв — `В Н Р С У` — единственные, где транслитерация расходится с начертанием
 * (`V N R S U` против `B H P C Y`). В данных они сегодня не встречаются ни разу,
 * поэтому выбор сделан по аналогии с остальными буквами и на данных НЕ ПРОВЕРЕН.
 * Если однажды номер с одной из них не сойдётся — смотреть надо сюда первым делом.
 */
const CYRILLIC_TO_LATIN: Readonly<Record<string, string>> = {
  А: 'A',
  Б: 'B',
  В: 'V',
  Г: 'G',
  Д: 'D',
  Е: 'E',
  Ж: 'J',
  З: 'Z',
  К: 'K',
  Л: 'L',
  М: 'M',
  Н: 'N',
  О: 'O',
  П: 'P',
  Р: 'R',
  С: 'S',
  Т: 'T',
  У: 'U',
  Ф: 'F',
  Х: 'X',
  Ц: 'C',
  Щ: 'Q',
  Э: 'E',
  Ю: 'U',
  Я: 'Y',
};

/** Разделители, которыми номер разбивают при ручном вводе. */
const SEPARATORS = /[\s\-_.]/g;

/** Любая кириллическая буква. Буквы вне таблицы выше оставляют номер ненормализованным. */
const CYRILLIC = /[Ѐ-ӿ]/;

/**
 * На что похож номер: буквенная серия и цифровая часть.
 *
 * Формы реестра — от `AA999999` до `AAAAA9999999`, то есть две-пять букв и шесть-девять
 * цифр. По этому шаблону решается, снимать ли префикс страны: `UZ` отбрасывается только
 * если остаток сам остаётся похож на номер.
 */
const LOOKS_LIKE_NUMBER = /^[A-Z]{2,5}[0-9]{6,9}$/;

/**
 * Приводит номер ВУ к каноническому виду.
 *
 * Верхний регистр, снятие разделителей, транслитерация кириллицы, снятие префикса
 * страны `UZ`. В реестре один и тот же номер лежит в двух написаниях — с префиксом
 * (21 634 профиля) и без (3 756), и это главный источник расхождений.
 *
 * Кириллическая буква, которой нет в таблице, оставляет номер ненормализованным:
 * функция возвращает исходную строку без изменений. Угадывать здесь нельзя — цена
 * ошибки в том, что два разных человека схлопнутся в одного.
 */
export function normalizeLicenseNumber(rawNumber: string): string {
  const uppercased = rawNumber.trim().toUpperCase().replace(SEPARATORS, '');

  const transliterated = [...uppercased]
    .map((character) => CYRILLIC_TO_LATIN[character] ?? character)
    .join('');

  if (CYRILLIC.test(transliterated)) {
    return rawNumber;
  }

  return stripCountryPrefix(transliterated);
}

/**
 * Снимает префикс страны `UZ` — но только если остаток остаётся похож на номер.
 * `UZ` перед семью цифрами префиксом не является: без букв это уже не номер.
 */
function stripCountryPrefix(number: string): string {
  if (!number.startsWith('UZ')) {
    return number;
  }

  const withoutPrefix = number.slice(2);

  return LOOKS_LIKE_NUMBER.test(withoutPrefix) ? withoutPrefix : number;
}

/**
 * Остался ли в номере кириллический символ, которого нет в таблице.
 * Такие номера считаются отдельно — в счётчике коллизий и в отчётах переноса.
 */
export function hasUnmappedCyrillic(rawNumber: string): boolean {
  return CYRILLIC.test(normalizeLicenseNumber(rawNumber));
}
