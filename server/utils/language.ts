import type { Language } from '#server/generated/prisma/enums';

/**
 * Язык, на котором система заговорит с человеком до того, как он выбрал сам.
 *
 * Узбекский — только по явному `uz`, всё остальное на русском. Правило одно на все двери:
 * `language_code` из `initData` в приложении, `from.language_code` у апдейта бота.
 *
 * Ошибиться здесь не страшно и поэтому сойдёт грубое правило: водитель переключает язык
 * на экране регистрации, и его выбор уезжает в `person_settings`, а сотрудник дальше
 * работает в приложении, где язык — настройка. Гадать тоньше по списку кодов Telegram
 * значит писать таблицу, которую никто никогда не проверит.
 */
export const preferredLanguage = (languageCode: string | undefined): Language =>
  languageCode === 'uz' ? 'uz' : 'ru';
