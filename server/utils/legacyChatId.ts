/**
 * Правило годного `chat_id` старой базы: 6–10 цифр и ничего больше.
 *
 * Живёт в `utils/`, а не рядом с сопоставлением, ровно по одной причине: тем же правилом
 * снимается эталон контрольных цифр в репозитории `legacyPublic`, а репозиторий не имеет
 * права ходить в сервисы (docs/principles.md → «Слои и зависимости»). Два описания одного
 * правила разъехались бы на первой же правке, и разъехались бы молча — сверка сравнивала
 * бы одно правило с другим, а не эталон с результатом.
 *
 * Семь записей старой базы правилу не отвечают: пустая строка, слово, обрезанный номер.
 * Боту такому водителю написать некуда.
 */

/**
 * Шаблон в виде строки — его читают оба движка: `RegExp` здесь и оператор `~` в SQL.
 *
 * Диалекты совпадают в нужной части: `\d` в POSIX-регулярках PostgreSQL — та же цифра,
 * `^` и `$` без флага `n` привязаны к началу и концу строки целиком, как и в JavaScript
 * без флага `m`.
 */
export const USABLE_CHAT_ID_PATTERN = '^\\d{6,10}$';

const USABLE_CHAT_ID = new RegExp(USABLE_CHAT_ID_PATTERN);

/** Разбирает `chat_id` в число или отвечает `null`, если писать по нему некуда. */
export const parseUsableChatId = (chatId: string | null): bigint | null =>
  chatId !== null && USABLE_CHAT_ID.test(chatId) ? BigInt(chatId) : null;
