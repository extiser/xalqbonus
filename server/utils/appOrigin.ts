import type { H3Event } from 'h3';

/**
 * Адрес приложения — схема и хост, на которые пришёл запрос (issue #267): из него собираются
 * ссылки на страницы приглашения и «задать пароль».
 *
 * Берётся из запроса, а не из переменной окружения: хост тот же, что у приложения, и на
 * локальном стеке это `http://localhost:3003`, а переменная рядом с доменом означала бы
 * вторую настройку, которую можно выставить вразнобой.
 *
 * Схему за входной дверью называет `X-Forwarded-Proto`: nginx и Caddy пробрасывают её вместе
 * с `Host` (docker/DEPLOY-MANUAL.md), без неё за прокси ссылка вышла бы на `http`.
 */
export const readAppOrigin = (event: H3Event): string =>
  getRequestURL(event, { xForwardedProto: true }).origin;
