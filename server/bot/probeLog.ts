import { consola } from 'consola';
import type { Bot } from 'grammy';

/**
 * РАЗВЕДКА issue #81. В `main` не уезжает — снимается вместе со страницей-заглушкой.
 *
 * Третья сторона опыта. Клиент видит статус, сервер видит `initData`, а куда при этом
 * попадает сам номер — не видно ни оттуда, ни отсюда: `registration.ts` разбирает контакт
 * и пишет ответ водителю, но что именно лежало в апдейте, в логе не остаётся.
 *
 * Поэтому апдейт печатается целиком и до всякой обработки. Штатная строка в
 * `instance.ts` печатает вид апдейта и `chat_id` — этого мало: вопрос ровно в составе
 * полей `message.contact` и в том, отличим ли контакт, присланный из Mini App, от контакта,
 * присланного кнопкой в чате.
 *
 * Обработчики регистрации не тронуты: наблюдатель стоит перед ними отдельным
 * middleware и только пишет в лог.
 *
 * **В логе окажется живой номер телефона** — тот, которым идёт опыт. Ещё одна причина,
 * по которой это остаётся в ветке.
 */

const log = consola.withTag('probe:bot');

export const registerProbeLogging = (bot: Bot): void => {
  bot.use(async (context, next) => {
    log.info('апдейт дословно', JSON.stringify(context.update));

    await next();
  });
};
