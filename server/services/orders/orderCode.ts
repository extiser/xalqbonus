import { randomInt } from 'node:crypto';

/**
 * Код заказа: пять цифр, которые водитель называет на стойке.
 *
 * Случайный, а не последовательный и не от времени. Последовательный код угадывается
 * соседним числом, а `Date.now()` у двух заказов, оформленных в одну секунду, совпадает —
 * то есть ровно там, где код и должен различать.
 *
 * Пяти цифр хватает, потому что уникальность требуется только среди висящих заказов:
 * частичный индекс освобождает коды выданных и отменённых, а висящих на весь парк десяток
 * (docs/decisions.md → «Каталог: заказ — это касса, остаток живёт по офисам»).
 *
 * `randomInt` из `node:crypto`, а не `Math.random()`: код называют вслух у стойки, и
 * предсказуемый генератор позволяет назвать чужой.
 */

const CODE_LENGTH = 5;
const CODE_UPPER_BOUND = 10 ** CODE_LENGTH;

export const generateOrderCode = (): string =>
  String(randomInt(CODE_UPPER_BOUND)).padStart(CODE_LENGTH, '0');
