import { randomInt } from 'node:crypto';

/**
 * Коды выдачи: пять цифр, которые водитель называет на стойке, — у заказа и у награды.
 *
 * Случайный, а не последовательный и не от времени. Последовательный код угадывается
 * соседним числом, а `Date.now()` у двух заказов, оформленных в одну секунду, совпадает —
 * то есть ровно там, где код и должен различать.
 *
 * Пяти цифр хватает, потому что уникальность требуется только среди висящих заказов:
 * частичный индекс освобождает коды выданных и отменённых, а висящих на весь парк десяток
 * (docs/decisions.md → «Каталог: заказ — это касса, остаток живёт по офисам»).
 *
 * **Заказы и награды разведены первой цифрой** (issue #172): заказ рождается с `0`–`4`,
 * награда — с `5`–`9`. У стойки одно поле на оба кода, и сотрудник не решает заранее, что
 * перед ним. Двух одинаковых кодов у стойки поэтому не существует: внутри таблицы уникальность
 * держит частичный индекс, между таблицами — непересечение диапазонов, и перекрёстной проверки
 * при рождении кода не нужно. Буква в начале и шестая цифра рассмотрены и отклонены: поле
 * кода отправляет запрос само по пятой цифре, и оба варианта ломают либо автопоиск, либо
 * цифровую клавиатуру. Половины диапазона хватает тем же доводом, что и пяти цифр: висящих
 * кодов единицы. Оба диапазона стоят и проверками в базе (`orders_code_range_check`,
 * `rewards_code_format_check`).
 *
 * `randomInt` из `node:crypto`, а не `Math.random()`: код называют вслух у стойки, и
 * предсказуемый генератор позволяет назвать чужой.
 */

const CODE_LENGTH = 5;

/** Сколько кодов в одном диапазоне первой цифры: пять цифр на пять первых — 50 000. */
const RANGE_SIZE = 5 * 10 ** (CODE_LENGTH - 1);

/** Начало диапазона наград: первая цифра 5. */
const REWARD_RANGE_START = RANGE_SIZE;

/** Код заказа: первая цифра `0`–`4`. */
export const generateOrderCode = (): string =>
  String(randomInt(RANGE_SIZE)).padStart(CODE_LENGTH, '0');

/** Код награды: первая цифра `5`–`9`. */
export const generateRewardCode = (): string =>
  String(REWARD_RANGE_START + randomInt(RANGE_SIZE));
