/**
 * Параметры входа сотрудников: секрет подписи cookie, сроки и пределы.
 *
 * Окружение читается напрямую, а не через `runtimeConfig` Nuxt, — по той же причине,
 * что у бота: `nuxt.config.ts` исполняется на сборке, образ собирается без `.env`,
 * и в бандл запеклась бы пустая строка. В воркере `useRuntimeConfig` не существует вовсе
 * (docs/decisions.md → «Окружение читается напрямую»).
 */

const readEnv = (name: string): string => (process.env[name] ?? '').trim();

/**
 * Секрет подписи cookie сессии.
 *
 * Пустое значение — не рабочее состояние, в отличие от пустого токена бота: приложение
 * без секрета не может ни выдать сессию, ни проверить её, и молчаливая работа «как будто
 * всё хорошо» означала бы вход, который подделывает кто угодно. Поэтому проверка стоит
 * в месте использования и роняет запрос с внятной строкой, а не на старте всего Nitro:
 * до появления сотрудников приложение обязано подниматься и без него.
 */
export const readSessionSecret = (): string => readEnv('EMPLOYEE_SESSION_SECRET');

/**
 * Сколько живёт cookie сессии.
 *
 * Тридцать суток: рабочий день сотрудника парка не кончается выходом из системы,
 * а выключение учётки и смена пароля гасят сессию немедленно и без всякого срока —
 * они читаются из базы на каждом запросе. Срок здесь ограничивает только украденный
 * cookie, про который мы ничего не узнали.
 */
export const SESSION_MAX_AGE_SECONDS = 30 * 24 * 60 * 60;

/** Сколько живёт приглашение. Не успел — выпускается новое (docs/decisions.md). */
export const INVITE_LIFETIME_MS = 48 * 60 * 60 * 1_000;

/**
 * Минимальная длина пароля. Проверяется на сервере: проверка в браузере — подсказка
 * человеку, а не ограничение.
 */
export const PASSWORD_MIN_LENGTH = 10;

/** После скольких неудач подряд связка «телефон + адрес» уходит в паузу. */
export const LOGIN_FAILURE_LIMIT = 5;

/**
 * Длина паузы и одновременно окно, за которое считаются неудачи.
 *
 * Пятнадцать минут: перебор пароля на такой паузе становится бессмысленным, а сотрудник,
 * честно забывший пароль с пятой попытки, ждёт обед, а не рабочий день.
 */
export const LOGIN_FAILURE_WINDOW_SECONDS = 15 * 60;
