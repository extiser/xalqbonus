import { createHash, randomBytes } from 'node:crypto';

/**
 * Токен одноразовой ссылки сотрудника: выпуск и хеш.
 *
 * Общий на приглашение сотрудника, ссылки к учётке (`employee_access_links`) и приглашение
 * в демо. Ищется ссылка по `sha256` от токена. Соли у хеша нет намеренно: токен — 32 случайных
 * байта, перебирать его словарём нечем, а без соли поиск по хешу остаётся одним индексным
 * запросом вместо перебора всех живых ссылок.
 *
 * Сам токен лежит рядом с хешем, пока ссылка жива, — чтобы её можно было скопировать снова
 * (docs/decisions.md → «Ссылка приглашения видна, пока жива»). Как ссылка собирается —
 * `employeeLinks.ts`.
 */

/**
 * Длина токена в байтах. 32 — столько же, сколько у секрета webhook: перебор такого
 * пространства не имеет смысла ни при каком сроке жизни ссылки.
 */
const TOKEN_BYTES = 32;

/**
 * `base64url`, а не hex: параметр `/start` у Telegram ограничен 64 знаками и допускает
 * только латиницу, цифры, дефис и подчёркивание. 32 байта в hex — это 64 знака, и вместе
 * с префиксом ссылки привязки или демо они в предел уже не влезают. В адресе страницы веба
 * тот же алфавит не требует экранирования.
 */
export const createInviteToken = (): string => randomBytes(TOKEN_BYTES).toString('base64url');

export const hashInviteToken = (token: string): string =>
  createHash('sha256').update(token).digest('hex');
