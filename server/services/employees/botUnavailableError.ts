/**
 * Бота нет — токен не задан, и ссылке на него вести некуда. Выпуск такой ссылки бессмыслен:
 * записанная в базу, она осталась бы живым токеном, которого никто не увидит.
 *
 * Бросают выпуск приглашения в демо и ссылки привязки Telegram сотрудника (issue #252, #267);
 * приглашение сотрудника ведёт в веб и бота не требует.
 */
export class BotUnavailableError extends Error {
  constructor() {
    super('токен бота не задан: ссылку на бота выписывать не на кого');
    this.name = 'BotUnavailableError';
  }
}
