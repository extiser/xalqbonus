import { formatDayKey } from '#server/utils/parkTime';

/**
 * Закрыт ли опрос по сроку на этот момент.
 *
 * `ends_on` — последний день опроса: «до 10 октября» значит до 10-го 23:59 включительно,
 * и закрыт он с 00:00 одиннадцатого по Ташкенту. Календарные сутки, а не сутки механики
 * с 05:00: опрос не связан с поездками (решение Руслана 02-10-2026). Поэтому сравнение идёт
 * с календарным днём парка (`formatDayKey`), а не с `parkDayKey`.
 *
 * Без срока — черновик — не закрыт: закрываться ему ещё не с чего.
 */
export const isSurveyClosed = (endsOn: string | null, moment: Date): boolean =>
  endsOn !== null && formatDayKey(moment) > endsOn;
