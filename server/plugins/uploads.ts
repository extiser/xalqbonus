import { consola } from 'consola';
import { readUploadsDir } from '#server/adapters/uploads/config';
import { ensureUploadsWritable } from '#server/adapters/uploads/productPhotos';

/**
 * Том с файлами проверяется на старте, а не первой загрузкой.
 *
 * Молчаливый отказ загрузки на проде с пустым или чужим томом не должен быть возможен:
 * обнаружился бы он тогда, когда сотрудник парка уже сидит перед формой и второй раз
 * выбирает ту же картинку (issue #120).
 *
 * Недоступный каталог роняет старт — в отличие от пустого токена бота, который рабочее
 * состояние: приложение без тома не умеет того, ради чего том заведён, и притворяться
 * работающим ему нечем. Проверка здесь же и заводит подкаталог фото: на пустом томе его
 * нет, а создание на первой загрузке означало бы, что права проверены поздно.
 *
 * Плагин синхронный, и проверка внутри тоже: асинхронный отказ Nitro не остановит —
 * он приезжает необработанным промисом после того, как сервер начал слушать порт
 * (`server/adapters/uploads/productPhotos.ts` → `ensureUploadsWritable`). Ошибка сначала
 * пишется в лог, потом уходит наверх: собранный образ печатает её стеком и падает, а
 * dev-сервер отдаёт исключение плагина в ответ на первый запрос, и в терминале не остаётся
 * ни строки — то же устройство, что у разбора режима бота.
 */
const log = consola.withTag('uploads');

export default defineNitroPlugin(() => {
  const dir = readUploadsDir();

  try {
    ensureUploadsWritable();
  } catch (error) {
    log.error('том с файлами недоступен: приложение не поднимается', {
      dir,
      error: error instanceof Error ? error.message : String(error),
    });

    throw error;
  }

  log.info('том с файлами на месте', { dir });
});
