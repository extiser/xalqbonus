import { consola } from 'consola';
import { APP_REQUIRED_ENV, findMissingEnv, MissingEnvError } from '#server/utils/requiredEnv';

/**
 * Обязательные переменные окружения проверяются на старте, до всех остальных плагинов.
 *
 * `00.` в имени — это порядок: Nitro подключает плагины по алфавиту пути, и проверка обязана
 * отработать раньше бота, очереди и тома, которые на эти переменные опираются.
 *
 * Приложение с незаполненной обязательной переменной поднималось здоровым и работало
 * наполовину: поломку находил человек, у которого что-то не сработало, а не лог (issue #153).
 * В лог уходит весь список недостающих сразу — иначе заполнение идёт по одной переменной
 * за перезапуск.
 *
 * Ошибка сначала пишется в лог, потом уходит наверх: собранный образ печатает её стеком
 * и падает, а dev-сервер отдаёт исключение плагина в ответ на первый запрос, и в терминале
 * не остаётся ни строки — то же устройство, что у тома (server/plugins/uploads.ts).
 */
const log = consola.withTag('env');

export default defineNitroPlugin(() => {
  const missing = findMissingEnv(APP_REQUIRED_ENV);

  if (missing.length > 0) {
    log.error('не заполнены обязательные переменные окружения — приложение не поднимается', { missing });

    throw new MissingEnvError(missing);
  }

  log.info('обязательные переменные окружения на месте');
});
