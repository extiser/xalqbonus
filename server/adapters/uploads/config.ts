/**
 * Том с файлами приложения: где он смонтирован.
 *
 * Что на него можно класть — типы и потолок размера — лежит в `shared/photo.ts`: те же числа
 * читает форма, и второй их набор на этой стороне разошёлся бы с первым молча.
 *
 * Окружение читается напрямую, а не через `runtimeConfig` Nuxt: `nuxt.config.ts` исполняется
 * на сборке, образ собирается без `.env`, и в бандл запеклась бы пустая строка
 * (docs/decisions.md → «Окружение читается напрямую»).
 *
 * Фото товаров — файлы на именованном томе, а не строки в базе и не объектное хранилище:
 * картинок в старом боте 105 на 8 МБ, и отдельная зависимость под них — лишняя
 * (docs/decisions.md → «Каталог: заказ — это касса, остаток живёт по офисам»).
 */

/**
 * Каталог тома. Умолчание совпадает с точкой монтирования в обоих compose-файлах:
 * переменная нужна тому, кто монтирует том иначе, а не каждому, у кого уже есть `.env`.
 *
 * Лежит он вне дерева приложения намеренно: дерево выката целиком уходит в контекст сборки
 * образа, и фото внутри него ездили бы в `docker build` каждым выкатом.
 */
export const readUploadsDir = (): string =>
  (process.env['UPLOADS_DIR'] ?? '').trim() || '/data/uploads';

/** Подкаталог фото товаров внутри тома. Он же первый сегмент `products.photo_path`. */
export const PRODUCT_PHOTO_DIR = 'products';
