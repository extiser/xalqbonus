#!/usr/bin/env bash
# Штатный выкат — единственный способ обновления прода. Образ собирается на самой машине
# из рабочего дерева и никуда не публикуется: реестра у проекта нет, конвейер GitHub Actions
# не заводится (issue #42).
# Использование: bash docker/scripts/deploy-manual.sh [REF]
# REF — git-ссылка (ветка, тег, SHA), по умолчанию origin/main.
set -Eeuo pipefail

# Путь считается от расположения самого скрипта, а не от текущего каталога: ниже идёт `cd`
# в каталог выката, да и вызывать скрипт можно откуда угодно. После передачи исполнения копии
# (следующий шаг) это уже каталог копии — оттуда же берутся _log.sh и _common.sh.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Журнал, общий на все серверные скрипты: log_info / log_warn / log_error, формат строки описан
# в самом файле. Подключается до передачи исполнения копии — та строка уже идёт в журнал.
# shellcheck source=_log.sh
source "${SCRIPT_DIR}/_log.sh"

# Подсказка по вызову — до всего остального: она ничего не меняет на машине и не должна тащить
# за собой ни копирование скрипта, ни переход в каталог выката, которого на машине разработчика
# нет. Идёт как есть, мимо формата журнала: адресована человеку у терминала прямо сейчас.
case "${1:-}" in
  -h | --help)
    # shellcheck source=_common.sh
    source "${SCRIPT_DIR}/_common.sh"
    cat <<USAGE
deploy-manual.sh — выкат прода: обновление дерева, дамп базы, сборка образа на сервере,
миграции, подъём стека, проверка готовности, запись версии, уборка.

  bash docker/scripts/deploy-manual.sh [REF]
  make prod-deploy [ref=<git-ссылка>]

  REF — ветка, тег или SHA; по умолчанию ${DEFAULT_REF}.

  Каталог выката: ${DEPLOY_DIR}
  Образ:          ${IMAGE_BASE}:<sha>
  Полка образов:  ${KEEP_TAGS_COUNT}

Переменные окружения (только для проверки уборки, в штатном выкате не задаются):
  PRUNE_DRY_RUN=1        уборка печатает, что сняла бы, и не трогает диск
  KEEP_TAGS_COUNT=<n>    глубина полки образов
  BUILD_CACHE_MAX_SIZE=<размер>  потолок приватной части кеша сборки

Разбор шагов и порядок отката — docker/DEPLOY-MANUAL.md.
USAGE
    exit 0
    ;;
esac

# --- Исполнение идёт из копии, а не из рабочего дерева ----------------------------------
# Скрипт лежит в рабочем дереве и первым же содержательным шагом это дерево обновляет
# (`git fetch` + `git reset --hard`) — то есть переписывает сам себя под исполняющим его bash.
# Bash читает сценарий не целиком, а порциями, запоминая позицию в файле: стоит длине
# измениться, и следующая порция читается не с той позиции — разбору достаётся обрывок.
# Отказ при этом выглядит произвольной синтаксической ошибкой посреди выката, а не понятным
# «файл изменился», и приходится он на середину: контейнер может быть уже погашен.
# Поэтому до подключения _common.sh и до любого шага скрипт копирует себя и соседей во временный
# каталог и передаёт исполнение копии. Копия лежит вне рабочего дерева, и обновление дерева её
# не касается: выкат доигрывает ту версию, которой был запущен.
#
# rollback.sh копированию не подлежит намеренно. Его зовёт сам выкат уже после обновления
# дерева, отдельным процессом, — и версия из обновлённого дерева там как раз правильная:
# откат должен идти по тем правилам, которые приехали с выкатываемым кодом. Себя он не
# переписывает (дерево не трогает), так что и защищать нечего. В том же положении pg-backup.sh.
#
# DEPLOY_SELF_COPY_DIR — признак «я уже копия» и одновременно путь для уборки. Без него
# копия скопировала бы себя снова, и так без конца.
if [ -z "${DEPLOY_SELF_COPY_DIR:-}" ]; then
  self_copy_dir="$(mktemp -d)"
  cp "${SCRIPT_DIR}/deploy-manual.sh" "${SCRIPT_DIR}/_common.sh" "${SCRIPT_DIR}/_log.sh" "$self_copy_dir/"
  export DEPLOY_SELF_COPY_DIR="$self_copy_dir"
  log_info старт "исполнение передано копии: ${self_copy_dir}"
  # Аргументы передаются как есть; переменные окружения переживают exec сами — процесс тот же.
  exec bash "${self_copy_dir}/deploy-manual.sh" "$@"
fi

# Каталог копии убирается за собой на любом выходе. Функция терпима к отсутствию каталога:
# её зовут и из обработчика выхода, и из обработчиков сигналов, и порядок между ними не
# гарантирован. Удаление каталога из-под работающего bash безопасно: файл сценария открыт
# по дескриптору, и отвязка имени его не закрывает.
remove_self_copy() {
  if [ -n "${DEPLOY_SELF_COPY_DIR:-}" ] && [ -d "$DEPLOY_SELF_COPY_DIR" ]; then
    rm -rf "$DEPLOY_SELF_COPY_DIR"
  fi
}

# Обработчик выхода возвращает исходный код: без явного `exit "$exit_code"` успешная уборка
# копии затёрла бы код нулём, и прерванный выкат отрапортовал бы успехом.
on_exit() {
  local exit_code=$?
  remove_self_copy
  exit "$exit_code"
}

# Прерывание без своего обработчика убивает bash сигналом, и EXIT-обработчик не отрабатывает
# вовсе — каталог копии остался бы на диске. Поэтому обработчик убирает его сам, снимает
# обработчики (иначе уборка пошла бы вторым кругом) и переизлучает сигнал: вызывающий видит
# честную смерть по сигналу, а не подменённый код возврата.
trap on_exit EXIT
trap 'trap - INT EXIT; remove_self_copy; kill -INT $$' INT
trap 'trap - TERM EXIT; remove_self_copy; kill -TERM $$' TERM

# Общая с rollback.sh часть: пути машины, полка образов, чтение последнего годного тега,
# запись IMAGE_TAG в .env и уборка. Берётся из каталога копии — рядом с исполняемым файлом.
# shellcheck source=_common.sh
source "${SCRIPT_DIR}/_common.sh"

REF="${1:-$DEFAULT_REF}"

# Каталог выката проверяется отдельной строкой, а не молчаливым `cd` под `set -e`: выкат,
# запущенный не на той машине, обязан сказать об этом словами, а не оборваться сообщением
# оболочки без единой строки журнала.
if ! cd "$DEPLOY_DIR"; then
  log_error старт "каталог выката ${DEPLOY_DIR} недоступен — выкат не начинался"
  exit 1
fi

log_info старт "выкат, ссылка ${REF}"

# 1. Обновить рабочее дерево.
# Каталог старого бота (/var/www/xalqbonusbot) и его процесс под pm2 отсюда не видны: выкат
# работает только внутри своего дерева.
log_info дерево "git fetch origin --prune"
git fetch origin --prune
log_info дерево "git reset --hard ${REF}"
git reset --hard "$REF"

SHA="$(git rev-parse --short HEAD)"
log_info дерево "рабочее дерево на ${SHA}"

# 2. Поднять зависимости и снять дамп базы перед миграцией (пока старая версия работает).
# pg-backup.sh снимает дамп через `compose exec postgres` — контейнер БД должен быть запущен,
# иначе выкат прервётся здесь и не дойдёт до миграции. Поднимаем только зависимости: app
# не стартует, схема ещё не приведена.
# `--wait` ждёт не старта контейнера, а его healthcheck'а (`pg_isready` у postgres): на чистом
# развёртывании том пуст, postgres несколько секунд создаёт кластер и всё это время отвечает
# «система запускается» — дамп и миграция следующим шагом упали бы в это окно. Предел времени
# явный: неподнявшаяся база останавливает выкат с ошибкой, а не подвешивает его навсегда.
log_info зависимости "up -d postgres redis, предел ожидания 90 с"
IMAGE_TAG="$SHA" docker compose -f "$COMPOSE_FILE" --env-file "$ENV_FILE" up -d --wait --wait-timeout 90 postgres redis

# Скрипт дампа берётся из обновлённого дерева, а не из каталога копии: он себя не переписывает,
# и версия, приехавшая с выкатываемым кодом, здесь как раз правильная.
log_info бэкап "снятие дампа перед миграцией"
bash docker/scripts/pg-backup.sh pre-migrate

# 3. Сборка образа на машине. Build-args нет: секреты приходят в runtime через env_file.
log_info сборка "docker build → ${IMAGE_BASE}:${SHA}"
docker build -f docker/Dockerfile -t "${IMAGE_BASE}:${SHA}" .

# 4. Применить миграции одноразовым контейнером собранного образа — до подъёма сервиса.
# Команда контейнера подменена, поэтому Nitro не стартует: ни трафика, ни BullMQ-воркеров.
log_info миграция "prisma migrate deploy одноразовым контейнером, IMAGE_TAG=${SHA}"
if ! IMAGE_TAG="$SHA" docker compose -f "$COMPOSE_FILE" --env-file "$ENV_FILE" run --rm -T app ./node_modules/.bin/prisma migrate deploy; then
  # Откат образа тут не нужен: новый код не поднимался, прод продолжает работать на прежней
  # версии. Дамп снят до старта миграции, и база могла мигрировать частично — восстановление
  # только руками, порядок в docker/DEPLOY-MANUAL.md.
  log_error миграция "prisma migrate deploy не прошла — выкат остановлен, прод на прежней версии"
  exit 1
fi

# 5. Поднять новый контейнер — на уже приведённой схеме.
log_info подъём "compose up -d, IMAGE_TAG=${SHA}"
IMAGE_TAG="$SHA" docker compose -f "$COMPOSE_FILE" --env-file "$ENV_FILE" up -d

# 6. Проверка готовности — 5 попыток с растущей паузой, суммарно до полутора минут.
# Проверяется /api/ready (готовность обслуживать), а не /api/health (здоровье процесса):
# поднявшийся Nitro с недоступной базой обслуживать не может, и выкат обязан это увидеть.
# Попыток пять, а не три: у образа start-period пробы — 60 с, и на первом развёртывании
# приложение честно занимает большую часть этого времени.
# Тело ответа в журнал не льётся: проверяется код ответа, а JSON проб посреди строк выката
# читать мешает.
log_info готовность "проверка /api/ready, попыток 5"
READY_OK=0
for attempt in 1 2 3 4 5; do
  if docker compose -f "$COMPOSE_FILE" --env-file "$ENV_FILE" exec -T app curl -sf -o /dev/null http://localhost:3000/api/ready; then
    log_info готовность "получена с попытки ${attempt}"
    READY_OK=1
    break
  fi
  if [ "$attempt" -eq 5 ]; then
    log_error готовность "не получена за 5 попыток — запускается откат"
  else
    log_warn готовность "не получена, попытка ${attempt}/5, пауза $((10 * attempt)) с"
    sleep $((10 * attempt))
  fi
done
if [ "$READY_OK" -eq 0 ]; then
  bash docker/scripts/rollback.sh
  exit 1
fi

# 7. Зафиксировать последний годный образ — только после зелёной готовности.
echo "$SHA" > "$LAST_GOOD_FILE"
log_info версия "последний годный образ записан в ${LAST_GOOD_FILE}: ${SHA}"

# 7б. Записать точный тег работающей версии в серверный .env (функция — в _common.sh).
# Без этой записи ручные `make prod-up` и `make prod-restart` подняли бы контейнер по тегу
# из .env — то есть по прежней версии, тихо откатив сервер. Неудача записи выкат не отменяет:
# он к этому моменту уже состоялся.
write_image_tag_to_env "$SHA" || log_warn версия "запись IMAGE_TAG в ${ENV_FILE} не отработала"

# 8. Уборка на диске: образы без тега, теги проекта сверх полки, кеш сборки сверх потолка
# (функции — в _common.sh). Исход выката она не меняет ни при какой неудаче.
run_disk_cleanup "$SHA"

log_info итог "выкат завершён на ${SHA}"
