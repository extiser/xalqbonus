#!/usr/bin/env bash
# Журнал серверных скриптов — выката, отката и копии базы. Строка журнала это четыре поля:
# время в UTC, уровень, шаг, факт.
#
#   [2026-09-08T15:41:14Z] INFO  уборка/образы   снят 5711e67
#
# Журнал читают постфактум и в аварии, поэтому в строке остаётся только произошедшее: устройство
# механизма объясняют комментарии рядом с кодом и docker/DEPLOY-MANUAL.md, а не вывод. Строка
# длиной в абзац читается дольше факта и вытесняет с экрана соседние.
#
# Три уровня: INFO — шаг прошёл, WARN — отказ, работу не отменяющий, ERROR — скрипт
# останавливается или запускает откат. Уровня между ними нет намеренно: читающему в аварии важно
# одно — продолжилась работа или нет.
#
# Шаг — короткое стабильное имя смыслового этапа, одно на все скрипты: старт, дерево,
# зависимости, бэкап, сборка, миграция, подъём, готовность, версия, уборка, уборка/образы,
# уборка/кеш, уборка/итог, откат, итог.
#
# Файл отдельный от _common.sh намеренно: подключение того тянет пути выката, а копию базы
# запускает ещё и таймер, где ничего этого нет. Здесь только вывод — ни переменных окружения,
# ни обращений к диску. Подключается через `source`: при подключении ничего не выполняет,
# в журнал не пишет и процесс не завершает.

# Ширина поля шага — в символах. Самое длинное имя сегодня короче; имя длиннее просто сдвинет
# факт своей строки, обрезки не происходит.
LOG_STEP_WIDTH=15

# Все три уровня пишут в stdout, а не разводятся по потокам: журнал читают целиком и по
# порядку, а строки двух потоков в одном файле переставляются местами из-за разной буферизации.
log_info() { log_line 'INFO' "$@"; }
log_warn() { log_line 'WARN' "$@"; }
log_error() { log_line 'ERROR' "$@"; }

# log_line <уровень> <шаг> <факт...>
log_line() {
  local level="$1" step="$2"
  shift 2

  # Отступ шага считается вручную по числу символов: ширина поля у printf в bash байтовая, а
  # имена шагов кириллические — от неё колонка разъезжается вдвое. Под LC_ALL=C длина считает
  # байты, и подстановка ниже оставляет от строки только продолжающие байты UTF-8 (10xxxxxx) —
  # их число и есть разница между байтами и символами.
  local LC_ALL=C
  local continuation_bytes="${step//[!$'\x80'-$'\xbf']/}"
  local step_width=$(( ${#step} - ${#continuation_bytes} ))
  local padding=""
  if [ "$step_width" -lt "$LOG_STEP_WIDTH" ]; then
    printf -v padding '%*s' "$(( LOG_STEP_WIDTH - step_width ))" ''
  fi

  printf '[%s] %-5s %s%s %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$level" "$step" "$padding" "$*"
}

# Файл предназначен для подключения, но запуск руками — первое, что делают, разбираясь
# в незнакомом каталоге. Пояснение печатается только при прямом запуске: при подключении
# `$0` — имя подключающего скрипта, и условие не выполняется.
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
  cat <<'USAGE'
_log.sh — журнал серверных скриптов, подключается через `source`, сам ничего не делает.

  source docker/scripts/_log.sh
  log_info старт "выкат, ссылка origin/main"
  log_warn версия "IMAGE_TAG не записан"
  log_error миграция "prisma migrate deploy не прошла"

Формат строки: [время UTC] УРОВЕНЬ шаг факт. Подробности — docker/DEPLOY-MANUAL.md.
USAGE
  exit 0
fi
