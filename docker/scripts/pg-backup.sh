#!/usr/bin/env bash
# Копия боевой базы: дамп через контейнер postgres, проверка снятого файла, ротация локальных
# копий. Запускается двумя путями — по расписанию (режим daily) и выкатом перед миграцией
# (режим pre-migrate), поэтому пути выката тут не подключаются и _common.sh не нужен.
#
# В режиме daily снимается ещё и архив тома `uploads` — фото товаров. Файлы лежат на томе,
# а не в базе, и дамп их не содержит: том, потерянный вместе с машиной, восстановить было бы
# нечем. В режиме pre-migrate файлы не трогаются: миграция базы им не угрожает, а выкат должен
# оставаться быстрым (issue #120).
#
# Баз на машине две, а не одна, — проверено 28-09-2026. Наша `xb` живёт в базе контейнера стека,
# и дамп снимается с неё целиком; после переноса старой базы там же лежит и копия `public`.
# Сам старый бот работает на системном Postgres машины (`sudo -u postgres`, база `xalqbonus`),
# и пока эта база есть, режим daily снимает и её — отдельным файлом на той же полке. Базы
# старого бота нет — шаг пропускается с записью в журнал: после выката это штатное состояние.
#
# Выгрузки за пределы машины нет: объектного хранилища у проекта пока нет, и вопрос этот
# отдельный (issue #42). Значит, единственная копия базы лежит на том же диске, что и сама
# база, — полки ниже это учитывают, а машина остаётся единственной точкой отказа.
set -Eeuo pipefail

# Журнал, общий на все серверные скрипты: log_info / log_warn / log_error, формат строки описан
# в самом файле. Путь считается от расположения скрипта: ниже идёт `cd` в каталог выката, а
# расписание зовёт скрипт по абсолютному пути из своего рабочего каталога.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=_log.sh
source "${SCRIPT_DIR}/_log.sh"

DEPLOY_DIR="/srv/xalqbonus"
COMPOSE_FILE="docker/compose.prod.yml"
ENV_FILE=".env"

# Дампы лежат вне каталога выката намеренно. Дерево выката целиком уходит в контекст сборки
# образа, и дампы внутри него ездили бы в docker build каждым выкатом — десятки мегабайт
# персональных данных парка в каждой сборке.
BACKUP_ROOT="/srv/xalqbonus-backups"

# Порог, ниже которого свободного места на диске остаётся тревожно мало. Дамп при этом всё
# равно снимается: отказ снимать копию — худшее, что можно сделать перед миграцией. Значение
# из критерия issue #42: после выката на диске не должно оставаться меньше десяти гигабайт.
DISK_FREE_WARN_GB=10

MODE="${1:-daily}"
case "$MODE" in
  -h | --help)
    cat <<USAGE
pg-backup.sh — дамп боевой базы (база контейнера целиком) и, пока она есть, базы старого бота.

  bash docker/scripts/pg-backup.sh [daily|pre-migrate]

  daily        копия по расписанию, ${BACKUP_ROOT}, хранится 14 последних;
               плюс архив тома uploads (фото товаров) — своя полка, тоже 14;
               плюс public базы старого бота из системного Postgres, если она есть, — тоже 14
  pre-migrate  копия перед миграцией, ${BACKUP_ROOT}/pre-migrate, хранится 10 последних
               (снимает сам выкат, руками звать не требуется). Файлы не трогает.

Дамп никуда не выгружается: объектного хранилища у проекта нет.
Восстановление из дампа и архива тома — docker/DEPLOY-MANUAL.md.
USAGE
    exit 0
    ;;
  daily)
    BACKUP_DIR="$BACKUP_ROOT"
    # Две недели ежедневных копий: боевой дамп на 07-09-2026 — 58 МБ, то есть полка занимает
    # около 0.8 ГБ при свободных на машине ~71 ГБ. Полку считаем от места, а не от срока
    # хранения: выгрузки за пределы машины нет, и копия старше двух недель ценна ровно тем,
    # что она есть.
    KEEP_LOCAL=14
    LABEL=""
    # Том с фото и база старого бота снимаются только этим режимом.
    BACKUP_UPLOADS=yes
    BACKUP_LEGACY=yes
    # Имя режима словами — для итоговой строки: её читают в системном журнале отдельно от
    # команды запуска, и `daily` там ничем не подкреплено.
    MODE_TITLE="по расписанию"
    ;;
  pre-migrate)
    BACKUP_DIR="${BACKUP_ROOT}/pre-migrate"
    # Десять копий перед миграцией — при выкате раз в несколько недель это история за всю
    # обозримую жизнь прода. Полка своя, а не общая с ежедневной: ежедневные копии не должны
    # вытеснять ту единственную, к которой возвращаются при неудачной миграции.
    KEEP_LOCAL=10
    LABEL="pre-migrate_"
    BACKUP_UPLOADS=no
    # Миграция трогает только базу контейнера: базе старого бота она не угрожает.
    BACKUP_LEGACY=no
    MODE_TITLE="перед миграцией"
    ;;
  *)
    log_error бэкап "неизвестный режим '${MODE}', допустимы: daily, pre-migrate"
    echo "Использование: bash docker/scripts/pg-backup.sh [daily|pre-migrate]" >&2
    exit 1
    ;;
esac

TS="$(date -u +%Y%m%d_%H%M%S)"
mkdir -p "$BACKUP_DIR"
if ! cd "$DEPLOY_DIR"; then
  log_error бэкап "каталог выката ${DEPLOY_DIR} недоступен — дамп не снят"
  exit 1
fi

# Имя базы и пользователь не зашиты — читаются из окружения контейнера, чтобы одна и та же
# команда работала на любом стенде. Пустое значение = контейнер не поднят или переменной нет;
# снимать дамп вслепую нельзя, выходим до записи файла.
DB_NAME="$(docker compose -f "$COMPOSE_FILE" --env-file "$ENV_FILE" exec -T postgres printenv POSTGRES_DB | tr -d '\r' || true)"
if [ -z "$DB_NAME" ]; then
  log_error бэкап "POSTGRES_DB не прочитан из контейнера postgres — дамп не снят"
  exit 1
fi

# Пустая база (развёртывание с нуля на пустых томах) даёт дамп в несколько сотен байт
# служебного заголовка — проверка размера ниже отвергла бы его и прервала выкат до миграции.
# Различить пустоту и оборванный дамп по размеру файла нельзя, поэтому спрашиваем состояние
# базы до дампа. Считаются обе наши схемы: `public` наполняется дампом старого бота в день
# выката, `xb` — миграциями, и пустой базой считается только та, где нет ни одной таблицы.
# Непрочитанный ответ (база недоступна, запрос упал, вернулось не число) — ошибка, а не
# пустота: иначе живая база с данными выглядела бы как пустая и выкат пошёл бы дальше без дампа.
TABLE_COUNT="$(docker compose -f "$COMPOSE_FILE" --env-file "$ENV_FILE" exec -T postgres \
  sh -c 'PGPASSWORD="$POSTGRES_PASSWORD" psql -U "$POSTGRES_USER" -d "$POSTGRES_DB" -tAc "SELECT count(*) FROM information_schema.tables WHERE table_schema IN ('"'"'public'"'"', '"'"'xb'"'"')"' \
  | tr -d '[:space:]' || true)"
case "$TABLE_COUNT" in
  '' | *[!0-9]*)
    log_error бэкап "число таблиц в ${DB_NAME} не получено, ответ '${TABLE_COUNT}' — дамп не снят"
    exit 1
    ;;
esac
if [ "$TABLE_COUNT" -eq 0 ]; then
  log_info бэкап "база ${DB_NAME} пуста, дампить нечего: таблиц в public и xb 0"
  exit 0
fi

DUMP_FILE="${BACKUP_DIR}/${DB_NAME}_${LABEL}${TS}.sql.gz"
log_info бэкап "pg_dump ${DB_NAME}, таблиц ${TABLE_COUNT}"

# Коды обеих команд конвейера проверяются по отдельности: под `set -o pipefail` виден только
# факт неудачи, а знать надо, что именно упало — снятие дампа или сжатие.
set +e +o pipefail
docker compose -f "$COMPOSE_FILE" --env-file "$ENV_FILE" exec -T postgres \
  sh -c 'PGPASSWORD="$POSTGRES_PASSWORD" pg_dump -U "$POSTGRES_USER" -d "$POSTGRES_DB"' \
  | gzip > "$DUMP_FILE"
PIPE_CODES=("${PIPESTATUS[@]}")
set -e -o pipefail
if [ "${PIPE_CODES[0]}" -ne 0 ] || [ "${PIPE_CODES[1]}" -ne 0 ]; then
  log_error бэкап "pg_dump не прошёл, коды pg=${PIPE_CODES[0]} gz=${PIPE_CODES[1]} — файл удалён"
  rm -f "$DUMP_FILE"
  exit 1
fi

# Целостность архива проверяется сразу: копия, о негодности которой узнают в день
# восстановления, — не копия.
if ! gzip -t "$DUMP_FILE"; then
  log_error бэкап "архив не проходит проверку gzip — файл удалён"
  rm -f "$DUMP_FILE"
  exit 1
fi

DUMP_SIZE="$(stat -c%s "$DUMP_FILE")"
if [ "$DUMP_SIZE" -lt 1000 ]; then
  log_error бэкап "дамп мал, ${DUMP_SIZE} б — файл удалён"
  rm -f "$DUMP_FILE"
  exit 1
fi
log_info бэкап "дамп снят: ${DUMP_FILE}, ${DUMP_SIZE} б"

# Ротация локальных копий своего режима: всё за пределом полки снимается. В журнал идёт
# случившееся — сколько файлов ушло и сколько лежит на диске после, — а не предел из настройки.
# Порядок задаёт сам шаблон: имена кончаются отметкой времени вида ГГГГММДД_ЧЧММСС, и разбор
# по алфавиту совпадает с разбором по времени. Файлов режима всегда хотя бы один — только что
# снятый, поэтому пустого разбора здесь не бывает.
MODE_DUMPS=("${BACKUP_DIR}/${DB_NAME}_${LABEL}"*.sql.gz)
ROTATED_COUNT=$(( ${#MODE_DUMPS[@]} - KEEP_LOCAL ))
if [ "$ROTATED_COUNT" -gt 0 ]; then
  rm -f "${MODE_DUMPS[@]:0:${ROTATED_COUNT}}"
else
  ROTATED_COUNT=0
fi
KEPT_COUNT=$(( ${#MODE_DUMPS[@]} - ROTATED_COUNT ))
log_info бэкап "ротация: удалено ${ROTATED_COUNT} · осталось ${KEPT_COUNT}"

# --- Архив тома с фото ---------------------------------------------------------------
#
# Фото товаров живут файлами на томе `uploads`, а не в базе, и дамп их не содержит вовсе
# (docs/decisions.md → «Фото товара — файл на именованном томе приложения»). Без этой копии
# состояние машины было бы такое: база восстанавливается целиком, а каталог открывается
# без единой картинки.
#
# Том снимается **одноразовым контейнером с монтированием только на чтение**, а не из живого
# контейнера приложения: копия не должна ни зависеть от того, поднят ли `app`, ни иметь
# возможности что-либо на томе изменить.
UPLOADS_NOTE="файлы не снимались"
if [ "$BACKUP_UPLOADS" = yes ]; then
  # Имя тома складывается docker'ом из имени проекта и имени тома: `name: xalqbonus-prod`
  # в compose.prod.yml плюс `uploads`. Записано строкой, потому что оба имени записаны строками
  # там же, а не вычисляются.
  UPLOADS_VOLUME="xalqbonus-prod_uploads"

  # Образ для tar — тот же, которым только что снят дамп. Он заведомо есть на машине, и ночная
  # копия не начинается тягой из реестра; ничего постгресового от него не требуется, нужен tar.
  # Берётся идентификатором работающего контейнера, а не строкой `postgres:16`: строка разошлась
  # бы с compose на первом же обновлении образа базы.
  TAR_IMAGE="$(docker compose -f "$COMPOSE_FILE" --env-file "$ENV_FILE" images -q postgres | head -n 1)"

  if [ -z "$TAR_IMAGE" ]; then
    log_error бэкап "образ контейнера postgres не определён — архив тома не снят"
    exit 1
  fi

  # Тома нет — это не «нечего копировать», а расхождение выката с compose: том заводится тем же
  # файлом, что и приложение. Молча пройти мимо значило бы оставить состояние «том есть,
  # копии нет» — ровно то, чего быть не должно.
  if ! docker volume inspect "$UPLOADS_VOLUME" >/dev/null 2>&1; then
    log_error бэкап "тома ${UPLOADS_VOLUME} нет — архив не снят, проверьте выкат compose.prod.yml"
    exit 1
  fi

  UPLOADS_FILE="${BACKUP_DIR}/uploads_${TS}.tar.gz"

  # Архив пишется в файл на хосте потоком со stdout контейнера: каталог копий внутрь
  # не монтируется вовсе, и контейнеру, кроме чтения тома, не дано ничего.
  if ! docker run --rm -v "${UPLOADS_VOLUME}:/data:ro" "$TAR_IMAGE" \
       tar -czf - -C /data . > "$UPLOADS_FILE"; then
    log_error бэкап "tar тома ${UPLOADS_VOLUME} не прошёл — файл удалён"
    rm -f "$UPLOADS_FILE"
    exit 1
  fi

  # Целостность — тем же способом, что у дампа. Проверки минимального размера здесь нет
  # намеренно: пустой том — законное состояние машины до первой загруженной картинки,
  # и архив на сотню байт от оборванного отличает как раз `gzip -t`, а не размер.
  if ! gzip -t "$UPLOADS_FILE"; then
    log_error бэкап "архив тома не проходит проверку gzip — файл удалён"
    rm -f "$UPLOADS_FILE"
    exit 1
  fi

  UPLOADS_SIZE="$(stat -c%s "$UPLOADS_FILE")"

  # Своя полка, а не общая с дампами: тома и дампы растут по-разному, и вытеснять друг друга
  # они не должны. Разбор по алфавиту совпадает с разбором по времени — имена кончаются той же
  # отметкой вида ГГГГММДД_ЧЧММСС.
  UPLOADS_ARCHIVES=("${BACKUP_DIR}/uploads_"*.tar.gz)
  UPLOADS_ROTATED=$(( ${#UPLOADS_ARCHIVES[@]} - KEEP_LOCAL ))
  if [ "$UPLOADS_ROTATED" -gt 0 ]; then
    rm -f "${UPLOADS_ARCHIVES[@]:0:${UPLOADS_ROTATED}}"
  else
    UPLOADS_ROTATED=0
  fi
  UPLOADS_KEPT=$(( ${#UPLOADS_ARCHIVES[@]} - UPLOADS_ROTATED ))

  log_info бэкап "архив тома снят: ${UPLOADS_FILE}, ${UPLOADS_SIZE} б · ротация: удалено ${UPLOADS_ROTATED} · осталось ${UPLOADS_KEPT}"
  UPLOADS_NOTE="${UPLOADS_FILE} · ${UPLOADS_SIZE} б"
fi

# --- Копия базы старого бота ----------------------------------------------------------
#
# Старый бот живёт на системном Postgres машины, а не в контейнере: его база `xalqbonus` —
# другая база, и дамп контейнера её не содержит. Пока она есть, это единственное место, где
# лежат балансы, которые переносятся в день выката, — копия снимается рядом с нашей, тем же
# расписанием, с той же проверкой и своей полкой.
#
# Снимается только `public`, форматом custom — ровно так, как его заливает
# restore-legacy-public.sh: копия годится и для отката, и для повторной заливки без обработки.
LEGACY_DB_NAME="xalqbonus"
LEGACY_NOTE="не снималась"

# Команды системного Postgres — от его пользователя и из корня: из каталога выката, куда
# у `postgres` нет доступа, каждая печатает предупреждение о рабочем каталоге.
legacy_postgres() {
  (cd / && sudo -u postgres "$@")
}

if [ "${BACKUP_LEGACY:-no}" = yes ]; then
  if ! id postgres >/dev/null 2>&1; then
    log_info бэкап "системного Postgres на машине нет — копия базы старого бота не снимается"
    LEGACY_NOTE="системного Postgres нет"
  else
    # Не ответивший сервер — предупреждение, а не остановка: копия нашей базы уже снята,
    # и ронять из-за чужой базы весь прогон незачем. Строка WARN видна в журнале.
    if ! LEGACY_EXISTS="$(legacy_postgres psql -X -tAc \
         "SELECT 1 FROM pg_database WHERE datname = '${LEGACY_DB_NAME}'" 2>&1)"; then
      log_warn бэкап "системный Postgres не ответил — копия базы старого бота не снята: ${LEGACY_EXISTS}"
      LEGACY_NOTE="системный Postgres не ответил"
    elif [ "$(echo "$LEGACY_EXISTS" | tr -d '[:space:]')" != "1" ]; then
      log_info бэкап "базы старого бота ${LEGACY_DB_NAME} в системном Postgres нет — копия не снимается"
      LEGACY_NOTE="базы нет"
    else
      LEGACY_FILE="${BACKUP_DIR}/legacy-public_${TS}.dump"

      if ! legacy_postgres pg_dump -Fc -n public "$LEGACY_DB_NAME" > "$LEGACY_FILE"; then
        log_error бэкап "pg_dump базы старого бота не прошёл — файл удалён"
        rm -f "$LEGACY_FILE"
        exit 1
      fi

      # Целостность — чтением архива целиком, а не только оглавления: оглавление custom-формата
      # лежит в начале файла, и оборванный хвост данных `pg_restore -l` не заметил бы.
      if ! pg_restore -f /dev/null "$LEGACY_FILE"; then
        log_error бэкап "дамп базы старого бота не читается pg_restore — файл удалён"
        rm -f "$LEGACY_FILE"
        exit 1
      fi

      LEGACY_SIZE="$(stat -c%s "$LEGACY_FILE")"
      if [ "$LEGACY_SIZE" -lt 1000 ]; then
        log_error бэкап "дамп базы старого бота мал, ${LEGACY_SIZE} б — файл удалён"
        rm -f "$LEGACY_FILE"
        exit 1
      fi

      # Своя полка, тем же правилом, что у дампов и архивов тома.
      LEGACY_DUMPS=("${BACKUP_DIR}/legacy-public_"*.dump)
      LEGACY_ROTATED=$(( ${#LEGACY_DUMPS[@]} - KEEP_LOCAL ))
      if [ "$LEGACY_ROTATED" -gt 0 ]; then
        rm -f "${LEGACY_DUMPS[@]:0:${LEGACY_ROTATED}}"
      else
        LEGACY_ROTATED=0
      fi
      LEGACY_KEPT=$(( ${#LEGACY_DUMPS[@]} - LEGACY_ROTATED ))

      log_info бэкап "дамп базы старого бота снят: ${LEGACY_FILE}, ${LEGACY_SIZE} б · ротация: удалено ${LEGACY_ROTATED} · осталось ${LEGACY_KEPT}"
      LEGACY_NOTE="${LEGACY_FILE} · ${LEGACY_SIZE} б"
    fi
  fi
fi

# Свободное место после копии — в журнал, а не в решение: диск делится со старым ботом и его
# базой, и заметить его исчерпание надо до того, как посреди выката упадёт сборка.
DISK_FREE_GB="$(df -BG --output=avail "$BACKUP_DIR" | tail -n 1 | tr -dc '0-9')"
if [ -n "$DISK_FREE_GB" ] && [ "$DISK_FREE_GB" -lt "$DISK_FREE_WARN_GB" ]; then
  log_warn бэкап "свободно ${DISK_FREE_GB} ГБ — меньше порога ${DISK_FREE_WARN_GB} ГБ"
fi

# Итог одной строкой: в прогоне по расписанию она последняя в системном журнале, и по ней
# судят об исходе всей копии — поэтому несёт режим, файл дампа, его размер, архив тома,
# копию базы старого бота и остаток места на диске. Том и старый бот названы и в режиме,
# который их не снимает: строка «не снимались» отвечает на вопрос, которого иначе не было бы
# видно вовсе.
log_info итог "копия ${MODE_TITLE} · ${DUMP_FILE} · ${DUMP_SIZE} б · том: ${UPLOADS_NOTE} · старый бот: ${LEGACY_NOTE} · свободно ${DISK_FREE_GB:-неизвестно} ГБ"
