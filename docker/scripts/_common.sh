#!/usr/bin/env bash
# Общая часть выката и отката: пути боевой машины, чтение и запись последнего годного тега,
# запись точного тега работающей версии в серверный .env и уборка образов на диске.
# Подключается через `source` из deploy-manual.sh и rollback.sh — файл только определяет
# функции и константы: при подключении ничего не выполняет, в журнал не пишет и процесс
# не завершает.
#
# Файл один, а не по файлу на тему: оба скрипта подключают его целиком и всегда, делить
# нечего — два файла с близкими именами только заставляли бы искать функцию в обоих.
#
# Требование к подключающему скрипту: подключённый _log.sh (журнал).
#
# Окружение одно — prod. Разбора имени окружения здесь нет и заводить его не надо: dev-контура
# у проекта не существует (docs/infra.md → «Два окружения»), а ветка кода, написанная про запас
# на второе окружение, до первого своего исполнения успевает разойтись с тем, что делает
# единственное настоящее.

# --- Пути и имена боевой машины --------------------------------------------------------

# Каталог выката — он же рабочее дерево репозитория на сервере и корень, в котором лежит
# серверный .env. Подкаталога с именем окружения нет: окружение одно.
# Старый бот живёт в /var/www/xalqbonusbot и выкатом не затрагивается ничем: ни файлы, ни
# процесс под pm2, ни его записи во входной двери машины отсюда не видны.
DEPLOY_DIR="/srv/xalqbonus"

# Файл боевого стека — относительно каталога выката, в который скрипты переходят до первого шага.
COMPOSE_FILE="docker/compose.prod.yml"

# Серверный .env — там же, в каталоге выката. Значение и compose-файлов, и Makefile:
# `--env-file .env` из корня дерева.
ENV_FILE=".env"

# Имя образа без реестра: образ собирается на самой машине и никуда не публикуется —
# ровно то же имя стоит в docker/compose.prod.yml.
IMAGE_BASE="xalqbonus"

# Ветка по умолчанию. Ветка у репозитория одна, релизной ветки нет.
DEFAULT_REF="origin/main"

# Файл последнего годного образа. Лежит в каталоге выката, в git не отслеживается,
# `git reset --hard` на шаге обновления дерева его не трогает.
LAST_GOOD_FILE="${DEPLOY_DIR}/.last_good_image_tag"

# --- Полка образов и кеша --------------------------------------------------------------

# Глубина полки образов — три версии: текущая, предыдущая для отката и запасная.
# Решение Руслана от 07-09-2026. Десять версий в OmniBox — не образец для подражания,
# а следствие частых выкатов: здесь выкат один и он в конце (docs/roadmap.md → «Выход
# в прод»), и полка живёт не ради истории, а ради одного шага назад.
# Переопределяется из окружения не ради настройки на ходу, а ради проверки: тегов на машине
# меньше полки, за полкой пусто, и ветка «за полкой, но неприкосновенен» не исполняется ни
# разу. В штатном выкате значение не задаётся.
KEEP_TAGS_COUNT="${KEEP_TAGS_COUNT:-3}"

# Потолок кеша сборки. Действует он не на весь кеш, а на его приватную часть — ту, что не
# разделяется с существующими образами: общие с образами слои движок не снимает, пока живы
# образы, которые их держат, и уходят они вместе с этими образами. Поэтому суммарный размер
# кеша после уборки всегда больше потолка, и это не признак того, что уборка не сработала —
# итоговая строка печатает обе части отдельно.
# Сборка идёт на сервере, и слои сборки истечения не имеют: `docker image prune` их не трогает,
# около гигабайта за сборку остаётся навсегда. Целиком кеш не сносится — он экономит минуты
# на каждой сборке.
# Переопределяется из окружения по той же причине, что и полка выше, — ради проверки.
BUILD_CACHE_MAX_SIZE="${BUILD_CACHE_MAX_SIZE:-5GB}"

# Сухой прогон уборки: любое непустое значение, кроме «0», печатает, что было бы снято, и
# ничего не удаляет. Нужен для первой проверки на боевой машине — единственном месте, где
# эту логику можно проверить по-настоящему.
PRUNE_DRY_RUN="${PRUNE_DRY_RUN:-0}"

# --- Последний годный образ ------------------------------------------------------------

# Последний годный тег или пустая строка. Пробелы и перевод строки снимаются.
read_last_good_tag() {
  [ -s "$LAST_GOOD_FILE" ] || return 0
  tr -d '[:space:]' < "$LAST_GOOD_FILE"
}

# --- Запись IMAGE_TAG в серверный .env -------------------------------------------------

# Переписать значение IMAGE_TAG в серверном .env на переданный тег.
# Правка точечная: меняется только значение, отступ и комментарий строки сохраняются,
# соседние переменные и порядок файла не трогаются; строки нет — она дописывается.
# Функция всегда возвращает 0: неудача записи логируется предупреждением и не должна
# отменять выкат или откат — они к этому моменту уже состоялись. Цена неудачи — ручные
# `make prod-*` поднимут прежний тег из .env.
write_image_tag_to_env() {
  local tag="$1"

  if [ ! -f "$ENV_FILE" ]; then
    log_warn версия "${ENV_FILE} не найден — IMAGE_TAG не записан"
    return 0
  fi

  local tmp_file
  if ! tmp_file="$(mktemp)"; then
    log_warn версия "временный файл не создан — IMAGE_TAG не записан"
    return 0
  fi

  # awk сохраняет строку целиком и подменяет только значение: префикс (отступ + `IMAGE_TAG=`)
  # и хвост (пробелы + комментарий) переносятся как есть. `cat > файл` вместо `mv` — чтобы
  # уцелели владелец и права .env (он лежит под пользователем выката, читается compose).
  if awk -v tag="$tag" '
      match($0, /^[ \t]*IMAGE_TAG=/) {
        prefix = substr($0, 1, RLENGTH)
        rest = substr($0, RLENGTH + 1)
        match(rest, /^[^ \t]*/)
        print prefix tag substr(rest, RLENGTH + 1)
        found = 1
        next
      }
      { print }
      END { if (!found) print "IMAGE_TAG=" tag }
    ' "$ENV_FILE" > "$tmp_file" && cat "$tmp_file" > "$ENV_FILE"; then
    log_info версия "IMAGE_TAG в ${ENV_FILE} → ${tag}"
  else
    log_warn версия "IMAGE_TAG=${tag} не записан в ${ENV_FILE}"
  fi

  rm -f "$tmp_file"
}

# --- Уборка на диске -------------------------------------------------------------------
# Зовёт её только выкат, а живёт она здесь потому, что стережёт откат: полка образов и список
# неприкосновенных существуют ради того, чтобы rollback.sh нашёл, на что возвращаться. Правило,
# защищающее образ, лежит рядом с правилом, которое этот образ ищет.
# Ни один шаг уборки не влияет на исход выката: он к этому моменту уже состоялся, любая
# неудача уборки — предупреждение в журнале, код возврата не меняется.

# Сухой прогон включён? Любое непустое значение, кроме «0».
is_prune_dry_run() {
  [ -n "$PRUNE_DRY_RUN" ] && [ "$PRUNE_DRY_RUN" != "0" ]
}

# Размер сущности из краткого `docker system df` по имени типа (`Images`, `Build Cache`).
# Размеры считает сам движок — человек, зашедший на машину руками, увидит те же числа.
docker_df_size() {
  local wanted_type="$1"
  docker system df --format '{{.Type}}|{{.Size}}' \
    | awk -F'|' -v wanted="$wanted_type" '$1 == wanted { print $2 }'
}

# Разбивка кеша сборки: сколько всего, сколько из этого разделяется с существующими образами
# и сколько занимает приватная часть. Печатает три поля через «|» в порядке
# «всего|общие|приватные»; поле, которого в выводе не оказалось, — «неизвестно».
# Источник — `docker buildx du`, а не краткая сводка `docker system df`: сводка знает только
# суммарный размер, а потолок уборки действует на приватную часть. Без разделения итоговая
# строка выглядит как «уборка не отработала» ровно тогда, когда уборка отработала точно.
build_cache_breakdown() {
  local raw_output
  raw_output="$(docker buildx du 2>/dev/null)" || raw_output=""

  printf '%s\n' "$raw_output" | awk '
    $1 == "Shared:"  { shared_size = $2 }
    $1 == "Private:" { private_size = $2 }
    $1 == "Total:"   { total_size = $2 }
    END {
      if (total_size == "")   { total_size = "неизвестно" }
      if (shared_size == "")  { shared_size = "неизвестно" }
      if (private_size == "") { private_size = "неизвестно" }
      printf "%s|%s|%s\n", total_size, shared_size, private_size
    }
  '
}

# Последняя непустая строка вывода команды, пробелы сжаты: движок кладёт в неё итог, годный
# журналу, а всё выше — портянка. `|| true` не декоративно: на пустом выводе grep возвращает
# единицу, и под `set -e` вызывающий шаг вышел бы с ошибкой — команда отработала бы, а в журнал
# ушло бы предупреждение.
last_output_line() {
  printf '%s\n' "$1" | grep -v '^[[:space:]]*$' | tail -n 1 | tr -s '[:blank:]' ' ' || true
}

# Шаг уборки, у которого содержательный итог — в последней строке вывода, а всё остальное
# портянка: `docker builder prune` печатает таблицу всех записей кеша, `docker image prune` —
# пару строк мимо формата журнала. Вывод перехватывается и в журнал уходит своей строкой
# только последняя («Total: …»). При неудаче команды вывод показывается целиком: причина
# в нём, а не в последней строке.
run_prune_step() {
  local step="$1" fact_prefix="$2"
  shift 2

  local command_output
  if ! command_output="$("$@" 2>&1)"; then
    log_warn "$step" "${fact_prefix} — команда не отработала, вывод целиком ниже"
    printf '%s\n' "$command_output"
    return 1
  fi

  local last_line
  last_line="$(last_output_line "$command_output")"
  log_info "$step" "${fact_prefix} — ${last_line:-вывод пуст}"
}

# Сколько тегов проекта лежит на машине сейчас.
count_project_tags() {
  docker image ls "$IMAGE_BASE" --format '{{.Tag}}' \
    | grep -c -v '^<none>$' || true
}

# Теги образов проекта, на которых прямо сейчас работают контейнеры машины.
# Движок и сам не даёт снять образ из-под запущенного контейнера, но защита эта — побочный
# эффект, а в журнале она выглядит сбоем («не снят»). Явный список делает намерение намерением
# и убирает пугающую строку.
running_project_image_tags() {
  docker ps --format '{{.Image}}' \
    | awk -v base="${IMAGE_BASE}:" 'index($0, base) == 1 { print substr($0, length(base) + 1) }'
}

# Неприкосновенные теги: текущий выкат, последний годный и теги работающих контейнеров.
# По строке на тег, без повторов.
collect_protected_tags() {
  local current_tag="$1"
  {
    printf '%s\n' "$current_tag"
    read_last_good_tag
    running_project_image_tags
  } | grep -v '^$' | sort -u
}

# Образы без тега: слои, оставшиеся без имени после пересборки того же коммита. Образы,
# помеченные `<sha>`, не dangling — им отдельный шаг ниже.
# Уборка машинная, а не только наша: у `docker image prune` фильтра по имени репозитория нет,
# потому что у образа без тега имени и нет. Снимаются только образы без тега, не используемые
# ни одним контейнером; старому боту это ничем не грозит — он работает под pm2 и образов
# на машине не держит.
prune_dangling_images() {
  if is_prune_dry_run; then
    local dangling_count
    dangling_count="$(docker image ls --filter dangling=true --quiet | grep -c . || true)"
    log_info уборка/образы "без тега — образов ${dangling_count}"
    return 0
  fi

  run_prune_step уборка/образы "без тега" docker image prune -f
}

# Предел хранения образов проекта.
# Тегированные образы уборкой мусора не снимаются — без этого шага каждый выкат оставлял бы
# на диске ещё один образ навсегда. Сохраняются KEEP_TAGS_COUNT последних тегов по дате
# создания, а также неприкосновенные — даже если те выпали из полки. Счёт по тегам, а не по
# идентификаторам образов: сборка на сервере вешает на выкат ровно один тег.
# Число снятых тегов отдаётся через PRUNED_TAGS_COUNT — итоговая строка печатает его рядом
# с размерами.
PRUNED_TAGS_COUNT=0
prune_old_project_images() {
  local current_tag="$1"
  local removal_error removal_reason
  local protected_tags
  protected_tags="$(collect_protected_tags "$current_tag")"

  local all_tags
  all_tags="$(docker image ls "$IMAGE_BASE" --format '{{.CreatedAt}}|{{.Tag}}' \
    | sort -r | cut -d'|' -f2 | grep -v '^<none>$' || true)"

  local tags_to_remove=""
  local tag_index=0
  local tag
  while IFS= read -r tag; do
    [ -n "$tag" ] || continue
    tag_index=$((tag_index + 1))
    if [ "$tag_index" -le "$KEEP_TAGS_COUNT" ]; then
      continue
    fi
    if printf '%s\n' "$protected_tags" | grep -Fxq -- "$tag"; then
      log_info уборка/образы "оставлен ${tag} — неприкосновенный, за полкой"
      continue
    fi
    tags_to_remove="${tags_to_remove}${tag}"$'\n'
  done <<< "$all_tags"

  if [ -z "$tags_to_remove" ]; then
    log_info уборка/образы "снимать нечего, полка ${KEEP_TAGS_COUNT}"
    return 0
  fi

  while IFS= read -r tag; do
    [ -n "$tag" ] || continue
    PRUNED_TAGS_COUNT=$((PRUNED_TAGS_COUNT + 1))
    # Сухой прогон печатает ту же строку, что и обычный прогон: режим объявлен один раз в начале
    # уборки, и повторять его в каждой строке значит удлинять их все ради одного заголовка.
    if is_prune_dry_run; then
      log_info уборка/образы "снят ${tag}"
      continue
    fi
    # Причина отказа берётся из вывода движка: теги работающих контейнеров уже в неприкосновенных,
    # и отказ здесь ничем в самом скрипте не объясняется.
    if removal_error="$(docker image rm "${IMAGE_BASE}:${tag}" 2>&1 >/dev/null)"; then
      log_info уборка/образы "снят ${tag}"
    else
      # Постоянная приставка движка снимается: она одинакова у всех отказов и только удлиняет
      # строку, а причина идёт следом за ней.
      removal_reason="$(last_output_line "$removal_error")"
      log_warn уборка/образы "не снят ${tag} — ${removal_reason#Error response from daemon: }"
    fi
  done <<< "$tags_to_remove"
}

# Потолок кеша сборки.
# Флаг именно `--max-used-space`: на Docker 29.7.2 `--keep-storage` отсутствует. Значение
# принимается в человеческом виде — `5GB` проходит, `5Gigs` отвергается ошибкой разбора суффикса.
prune_build_cache() {
  # Разбивку кеша числами печатает итоговая строка ниже — одинаково в обоих прогонах, поэтому
  # сухому прогону остаётся назвать потолок.
  if is_prune_dry_run; then
    log_info уборка/кеш "потолок приватной части ${BUILD_CACHE_MAX_SIZE}"
    return 0
  fi

  run_prune_step уборка/кеш "потолок приватной части ${BUILD_CACHE_MAX_SIZE}" \
    docker builder prune -f --max-used-space "$BUILD_CACHE_MAX_SIZE"
}

# Итог цифрами: перечень снятых тегов сам по себе не говорит, что с диском.
# Кеш сборки печатается разбивкой, а не одним числом: потолок действует на приватную часть, и
# суммарный размер рядом с потолком читался бы как невыполненная уборка.
# Свободное место на разделе печатается тем же шагом: 80 ГБ на машине делятся со старым ботом
# и его базой, и один только размер наших образов о запасе не говорит.
log_prune_summary() {
  local kept_count images_size disk_free
  kept_count="$(count_project_tags)" || kept_count="неизвестно"
  images_size="$(docker_df_size 'Images')" || images_size="неизвестно"
  disk_free="$(df -h "$DEPLOY_DIR" | awk 'NR == 2 { print $4 }')" || disk_free="неизвестно"

  local cache_total cache_shared cache_private
  IFS='|' read -r cache_total cache_shared cache_private <<< "$(build_cache_breakdown)"

  log_info уборка/кеш "всего ${cache_total} · общий ${cache_shared} · приватный ${cache_private} · потолок ${BUILD_CACHE_MAX_SIZE}"
  log_info уборка/итог "снято тегов ${PRUNED_TAGS_COUNT} · хранится ${kept_count:-неизвестно} · образы ${images_size:-неизвестно} · свободно на диске ${disk_free:-неизвестно}"
}

# Вся уборка одним вызовом: выкату остаётся позвать её после того, как версия записана.
# Сухой прогон объявляется один раз, а не повторяется в каждой строке: строки от этого
# одинаковы в обоих прогонах, и режим читается там, где начинается.
run_disk_cleanup() {
  local current_tag="$1"

  if is_prune_dry_run; then
    log_info уборка "сухой прогон, диск не трогается: PRUNE_DRY_RUN=${PRUNE_DRY_RUN}"
  fi

  prune_dangling_images || log_warn уборка/образы "снятие образов без тега не отработало"
  prune_old_project_images "$current_tag" || log_warn уборка/образы "снятие старых тегов не отработало"
  prune_build_cache || log_warn уборка/кеш "уборка кеша не отработала"
  log_prune_summary || log_warn уборка/итог "итог не собрался"
}

# Файл предназначен для подключения, но запуск руками — первое, что делают, разбираясь
# в незнакомом каталоге. Пояснение печатается только при прямом запуске: при подключении
# `$0` — имя подключающего скрипта, и условие не выполняется.
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
  cat <<USAGE
_common.sh — общая часть выката и отката, подключается через \`source\` после _log.sh
и сама ничего не делает.

  Каталог выката:        ${DEPLOY_DIR}
  Файл стека:            ${COMPOSE_FILE}
  Серверный .env:        ${DEPLOY_DIR}/${ENV_FILE}
  Образ:                 ${IMAGE_BASE}:<sha>
  Ссылка по умолчанию:   ${DEFAULT_REF}
  Последний годный тег:  ${LAST_GOOD_FILE}
  Полка образов:         ${KEEP_TAGS_COUNT}
  Потолок кеша сборки:   ${BUILD_CACHE_MAX_SIZE}

Выкат — docker/scripts/deploy-manual.sh, откат — docker/scripts/rollback.sh,
порядок и разбор шагов — docker/DEPLOY-MANUAL.md.
USAGE
  exit 0
fi
