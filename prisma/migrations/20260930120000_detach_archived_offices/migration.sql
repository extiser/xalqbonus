-- Архивные офисы теряют закреплённых (issue #303, решение Руслана 30-09-2026).
--
-- С этого выпуска архивация сама удаляет строки `employee_offices` офиса
-- (`setOfficeArchived.ts`), а закрепить за архивным офисом нельзя. Здесь то же для офисов,
-- архивированных раньше: иначе закреплённый менеджер так и работал бы в закрытом офисе.
-- Возврат из архива закреплений не возвращает — закрепляют заново на странице офиса.
--
-- Prisma генерирует DDL без квалификации схемой и полагается на search_path соединения.
-- Ставим его явно: миграция не должна уехать в `public` ни при каких условиях.
SET search_path TO "xb";

DELETE FROM "employee_offices"
 WHERE "office_id" IN (SELECT "id" FROM "offices" WHERE "archived_at" IS NOT NULL);
