-- Номер в журнале попыток становится необязательным.
--
-- При исходе `contact_not_own` номер принадлежит человеку, который боту ничего не присылал
-- и о программе не знает: хранить его незачем, а счёт попыток от этого не страдает. Писался
-- он до сих пор пустой строкой — и это ровно та подмена, из-за которой запрос «попытки без
-- номера» приходится писать с оглядкой: пустая строка означает «номер был, и он пустой»,
-- а нам нужно «номера не было».
--
-- Отдельной миграцией от `20260912090000_link_closed_in_history`, а не дописыванием в неё:
-- та уже применена, и правка её файла разошлась бы с контрольной суммой в `_prisma_migrations`
-- — Prisma отказалась бы накатывать что-либо дальше.
--
-- Строки с пустой строкой в колонке переводятся в `NULL` тем же проходом. Взяться они могли
-- ровно из одного места — прогонов регистрации после предыдущей миграции этой же ветки:
-- до неё в `phone_raw` писался настоящий номер, а пустой номер не проходит проверку строки
-- контакта и до журнала не доезжает. Оставить их значило бы сохранить в таблице ту самую
-- двусмысленность, ради снятия которой колонка и стала необязательной.
--
-- Prisma генерирует DDL без квалификации схемой и полагается на search_path соединения.
-- Ставим его явно: миграция не должна уехать в `public` ни при каких условиях.
