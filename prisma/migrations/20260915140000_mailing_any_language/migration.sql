-- Рассылке достаточно текста на одном языке — любом (решение Руслана 15-09-2026, PR #149).
--
-- Прежде русский текст был обязателен, а узбекский нет. Рассылка только на узбекском — рабочий
-- случай: парк пускает два отдельных сообщения или обращается только к узбекоязычным.
-- Аудитория по языку при этом не режется — сообщение уходит всем участникам программы.
--
-- Отдельной миграцией, а не правкой `20260915081134_drafts`: та уже применена к локальной
-- и тестовой базе, и правка применённой миграции ломает её контрольную сумму.
--
-- Prisma генерирует DDL без квалификации схемой и полагается на search_path соединения.
-- Ставим его явно: миграция не должна уехать в `public` ни при каких условиях.
SET search_path TO "xb";

-- У всего, что не черновик, есть заголовок и текст хотя бы на одном языке. Пустое по-прежнему
-- пишется NULL, а не пробелами.
ALTER TABLE "mailings" DROP CONSTRAINT "mailings_texts_check";

ALTER TABLE "mailings" ADD CONSTRAINT "mailings_texts_check"
    CHECK (
        ("title" IS NULL OR btrim("title") <> '')
        AND ("text_ru" IS NULL OR btrim("text_ru") <> '')
        AND ("text_uz" IS NULL OR btrim("text_uz") <> '')
        AND ("status" = 'draft'
             OR ("title" IS NOT NULL AND ("text_ru" IS NOT NULL OR "text_uz" IS NOT NULL)))
    );
