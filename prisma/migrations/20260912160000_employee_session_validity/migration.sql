-- Отметка годности выданных cookie сотрудника.
--
-- До этой миграции годность решал `password_changed_at`: cookie, выпущенный раньше отметки,
-- считался недействительным. Выход из веба погасить сессию этим способом не мог — пароль
-- при выходе не меняется, — и кнопка «Выйти» убирала cookie из браузера, оставляя
-- сохранённое до выхода значение годным все тридцать суток.
--
-- Поэтому годность переезжает в своё поле, а `password_changed_at` остаётся тем, чем назван:
-- временем последней смены пароля. Обновляют отметку оба события — и выход, и смена пароля,
-- — но проверяется она одна. Двух полей, которые проверяются вместе и означают одно и то же,
-- быть не должно: третий способ погасить сессии допишут в одно из них и забудут про второе
-- (issue #102).
--
-- Backfill из `password_changed_at` обязателен: без него уже погашенные сменой пароля cookie
-- ожили бы этой миграцией.
--
-- Prisma генерирует DDL без квалификации схемой и полагается на search_path соединения.
-- Ставим его явно: миграция не должна уехать в `public` ни при каких условиях.
SET search_path TO "xb";

-- AlterTable
ALTER TABLE "employees" ADD COLUMN "sessions_valid_from" TIMESTAMPTZ(6);

UPDATE "employees"
   SET "sessions_valid_from" = "password_changed_at"
 WHERE "password_changed_at" IS NOT NULL;
