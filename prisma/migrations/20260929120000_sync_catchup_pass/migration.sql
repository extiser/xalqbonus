-- Догоняющий прогон идёт проходами, проход режется на куски (issue #286).
--
-- Неделю одним прогоном лимит Fleet API не отпускает, а упавший прогон начинал следующий
-- с первой страницы — догон на проде не проходил ни разу. Теперь границы прохода
-- фиксируются при его начале, куски идут от старых к новым, и `watermark` у `orders_catchup`
-- означает позицию прохода: конец последнего пройденного куска.
--
-- Колонки пустые у всех видов, кроме `orders_catchup`. У существующей строки догона (если
-- она есть) обе остаются пустыми: прохода нет, и первый же запуск начнёт новый.
--
-- Prisma генерирует DDL без квалификации схемой и полагается на search_path соединения.
-- Ставим его явно: миграция не должна уехать в `public` ни при каких условиях.
SET search_path TO "xb";

ALTER TABLE "sync_state" ADD COLUMN "pass_from" TIMESTAMPTZ(6),
ADD COLUMN "pass_to" TIMESTAMPTZ(6);
