--
-- Своей причиной, а не `campaign`: кампания раздаёт баллы по решению парка всем в списке
-- разом, опрос платит за действие самого водителя, по одному. Ключ —
-- `survey:<surveys.id>:<persons.id>`, рассылки в нём нет: один опрос уходит несколькими
-- рассылками, а платится один раз (docs/points.md → «Баллы за опрос»).
--
-- Prisma генерирует DDL без квалификации схемой и полагается на search_path соединения.
-- Ставим его явно: миграция не должна уехать в `public` ни при каких условиях.
SET search_path TO "xb";

