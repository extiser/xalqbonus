-- Привязка Telegram, перенесённая из старой базы.
--
-- Словарь `link_confirmed_by` заведён миграцией ядра под три способа подтверждения,
-- существующие в новой системе: автоматически по телефону, оператором в офисе, ответом
-- самого водителя. Четвёртого — «пришла из старой системы» — среди них нет, а 4 091
-- привязка при переносе берётся именно оттуда.
--
-- Писать им `operator` нельзя: это утверждение, что привязку подтвердил человек в офисе,
-- глядя на документы. Оно неверно для всех 4 091 строки, и через год по нему нельзя будет
-- отличить настоящую проверку оператора от наследства.
--
-- Значение здесь только заводится. Использовать его в этой же миграции PostgreSQL
-- не даёт: новое значение enum недоступно в транзакции, где оно добавлено, — пишет
-- его скрипт переноса, отдельным прогоном.
SET search_path TO "xb";

ALTER TYPE "link_confirmed_by" ADD VALUE 'legacy_import';
