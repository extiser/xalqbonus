-- Строки ответа отделяются от различных профилей в деталях прогона реестра.
--
-- До этой миграции `profiles_seen`, `profiles_inserted` и `profiles_updated` считали
-- строки ответов API, а не профили. У инкрементального прогона это одно и то же — он
-- идёт одним проходом, — а у полного обхода нет: кусок крупнее 3 000 берётся с двух
-- концов, половины перекрываются намеренно, и профиль из прохода `asc` считался снова
-- в `desc`. Отсюда «увидено 29 345» и «обновлено 29 345» при 25 391 профиле в парке.
--
-- Колонка, означающая у одного вида прогона профили, а у другого строки ответа, делает
-- свод за период бессмысленным: он складывает несравнимое. Поэтому три прежних счётчика
-- отныне считают различные профили, а цена нарезки переезжает в свою колонку.
--
-- Строка обхода после этого читается как «0 новых, 25 391 подтверждён, 29 345 строк
-- ответа», и каждое из трёх чисел отвечает на свой вопрос.
--
-- Прошлые строки не пересчитываются: у прогонов, прошедших до этой миграции, различных
-- профилей взять неоткуда, а досочинять их значило бы соврать в журнале. У них
-- `response_rows` остаётся нулём, и это честно отличает «строк не считали» от «строк ноль».
--
-- Prisma генерирует DDL без квалификации схемой и полагается на search_path соединения.
-- Ставим его явно: миграция не должна уехать в `public` ни при каких условиях.
SET search_path TO "xb";

-- AlterTable
ALTER TABLE "sync_run_registry" ADD COLUMN     "response_rows" INTEGER NOT NULL DEFAULT 0;
