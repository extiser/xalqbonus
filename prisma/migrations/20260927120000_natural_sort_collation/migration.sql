-- Естественный порядок имён (issue #257): числа внутри строки — по значению, а не по символам.
-- Состав демо-сегмента шёл «ДЕМО ВОДИТЕЛЬ 1, 10, 2, 3…» — сопоставление по умолчанию сравнивает
-- цифры как текст.
--
-- ICU с числовой сортировкой (`kn`) — из образа `postgres:16`, отдельных расширений не нужно.
-- Корневая локаль (`und`): имена и латиницей, и кириллицей, и порядок букв у неё тот же, что
-- у сопоставления базы, — меняется только то, как читаются цифры.
--
-- Prisma сопоставлений не описывает — объект заводится руками и живёт в схеме `xb`.
SET search_path TO "xb";

CREATE COLLATION "natural_sort" (provider = icu, locale = 'und-u-kn');
