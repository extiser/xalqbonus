-- Строки ответа у прогонов реестра, записанных прежним кодом.
--
-- Предыдущая миграция починила единственный полный обход. Рядом остались прогоны,
-- у которых `response_rows` лежит нулём просто потому, что колонки тогда не было:
-- строка показывает «строк ответа 0» там, где их было 582. Это та же неправда
-- в данных, что и у обхода, только меньшего размера.
--
-- Восстанавливается она из самой строки, без внешних чисел. Прежний код писал
-- в `profiles_seen` сумму `page.received`, то есть строки ответов; значит, у любого
-- старого прогона `response_rows` равен тому, что лежит в `profiles_seen`.
--
-- Осталось убедиться, что в `profiles_seen` строки и профили — это одно и то же число.
-- Доказательство внутри строки: `profiles_inserted + profiles_updated` прежний код
-- считал по каждой записи ответа, и совпадение этой суммы с `profiles_seen` означает,
-- что ни один профиль не пришёл дважды и ни один не остался неразобранным. Совпало —
-- различных профилей ровно столько же, и трогать первые три счётчика не нужно.
-- Не совпало — трогать строку нечем, и она остаётся как есть.
--
-- Полного обхода это не касается: у него сумма с `profiles_seen` не сходится
-- по построению, ради чего предыдущая миграция и написана.
--
-- Prisma генерирует DDL без квалификации схемой и полагается на search_path соединения.
-- Ставим его явно: миграция не должна уехать в `public` ни при каких условиях.
SET search_path TO "xb";

UPDATE "sync_run_registry" AS detail
   SET "response_rows" = detail."profiles_seen"
  FROM "sync_runs" AS run
 WHERE run."id" = detail."run_id"
   AND run."kind" = 'registry'
   AND detail."response_rows" = 0
   AND detail."profiles_seen" > 0
   AND detail."profiles_inserted" + detail."profiles_updated" = detail."profiles_seen";
