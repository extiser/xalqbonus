-- Выключенные учётки снимаются со всех офисов (issue #291, решение Руслана 29-09-2026).
--
-- С этого выпуска выключение само удаляет строки `employee_offices` учётки
-- (`setEmployeeDisabled.ts`). Здесь то же для учёток, выключенных раньше: иначе они так
-- и остались бы в составе офисов строкой, которая ничего не значит. Включение закреплений
-- не возвращает — закрепляют заново на странице офиса.
--
-- Prisma генерирует DDL без квалификации схемой и полагается на search_path соединения.
-- Ставим его явно: миграция не должна уехать в `public` ни при каких условиях.
SET search_path TO "xb";

DELETE FROM "employee_offices"
 WHERE "employee_id" IN (SELECT "id" FROM "employees" WHERE "disabled_at" IS NOT NULL);
