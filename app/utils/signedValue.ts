/**
 * Знак изменения на плитках веба — по первому символу строки: `+8,3 млн`, `−0,4 млн`.
 *
 * Кодекс веба: алый и зелёный — только у числа со знаком (`_reference/design/web/codex.md`,
 * «Правила, добавленные на экранах дашборда»). Число без знака алым читается как минус, даже
 * если это просто значение, поэтому компонент, не нашедший знака, цветом его не рисует.
 *
 * Минус принимается и типографский (`−`), и дефисом: в макетах стоит первый, а строку собирает
 * код, и дефис из `Intl` или шаблона не должен молча гасить цвет.
 */
export type ValueSign = 'plus' | 'minus';

export function valueSign(value: string): ValueSign | null {
  const first = value.trimStart().charAt(0);

  if (first === '+') {
    return 'plus';
  }

  if (first === '−' || first === '-') {
    return 'minus';
  }

  return null;
}
