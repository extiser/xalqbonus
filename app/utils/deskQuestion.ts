/**
 * Вопрос подтверждения выдачи у стойки — с именем водителя (issue #172).
 *
 * Сверка человека — единственная защита от промаха по клавише: опечатка в коде попадает
 * в чужой действующий код при любом формате, и ловится она только тем, что сотрудник видит
 * имя в самом вопросе, а не строкой выше.
 *
 * Имя стоит после «водителю» как есть, без склонения: имена приходят из реестра парка, узбекские
 * и русские вперемешку, и склонять их правилом значило бы однажды исказить. Имени в профиле
 * нет — вопрос просит сверить позывной.
 */
export const deskIssueQuestion = (driverName: string | null, subject: string): string =>
  driverName
    ? `Выдать ${subject} водителю ${driverName}?`
    : `Выдать ${subject}? Имени в профиле нет — сверьте позывной.`;
