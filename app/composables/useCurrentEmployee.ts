import type { Ref } from 'vue';
import type { EmployeeIdentity } from '#shared/types/employee';

/**
 * Кто вошёл — один ответ на всё приложение.
 *
 * Спрашивается в общей проверке маршрута — на каждом переходе, — и между переходами живёт
 * в состоянии: шапке нужно имя, разметке — роль, и ходить за ними в ручку из каждого
 * компонента значило бы десяток одинаковых запросов на один экран.
 *
 * Поводом пропустить проверку заполненное состояние не является и являться не может: здесь
 * лежит последний ответ сервера, а не разрешение (docs/principles.md → «Доверие к входным
 * данным»). Пока за этим ответом не сходили заново, он говорит о прошлом — о роли, которую
 * с тех пор сменили, и об учётке, которую с тех пор выключили (`#117`).
 */
export const useCurrentEmployee = (): Ref<EmployeeIdentity | null> =>
  useState<EmployeeIdentity | null>('current-employee', () => null);

/**
 * Одна строка о том, почему человек оказался на входе, когда сам он туда не просился.
 *
 * Писатель у состояния один — смена пароля: там объяснение рождается на клиенте, после
 * удачного ответа ручки, и до формы входа доезжает переходом внутри приложения. Отказ
 * общей проверки маршрута сюда не пишется, он уезжает кодом в адресе: на холодной загрузке
 * тот переход — `302`, браузер идёт за `/login` вторым запросом, и память первого до формы
 * не доживает. Два способа доставки в одно состояние однажды уже разошлись (`#115`).
 *
 * Выход сюда не пишет ничего: нажавшему «Выйти» форма входа и есть ответ.
 */
export const useAccessNotice = (): Ref<string | null> =>
  useState<string | null>('access-notice', () => null);
