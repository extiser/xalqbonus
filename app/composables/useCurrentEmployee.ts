import type { Ref } from 'vue';
import type { EmployeeIdentity } from '#shared/types/employee';

/**
 * Кто вошёл — один ответ на всё приложение.
 *
 * Спрашивается один раз на загрузку страницы, в общей проверке маршрута, и дальше живёт
 * в состоянии: шапке нужно имя, разметке — роль, и ходить за ними в ручку из каждого
 * компонента значило бы десяток одинаковых запросов на один экран.
 *
 * Живёт это состояние ровно до перезагрузки страницы, и на большее не годится: доступ
 * решает сервер на каждом запросе, а здесь лежит его последний ответ, не более того
 * (docs/principles.md → «Доверие к входным данным»).
 */
export const useCurrentEmployee = (): Ref<EmployeeIdentity | null> =>
  useState<EmployeeIdentity | null>('current-employee', () => null);

/**
 * Одна строка о том, почему человек оказался на входе: вышел сам, сменил пароль,
 * учётку выключили.
 *
 * Без неё выход и смена пароля выглядят одинаково — пустой формой входа, — и человек
 * не понимает, случилось ли то, что он делал.
 */
export const useAccessNotice = (): Ref<string | null> =>
  useState<string | null>('access-notice', () => null);
