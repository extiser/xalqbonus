/**
 * Ограничения фото товара: что принимается и какого размера.
 *
 * Лежат в `shared/`, потому что читают их обе стороны, и это не удобство, а требование.
 * Ограничение поля живёт в форме — `accept` в диалоге выбора и проверка размера при выборе
 * файла, — а сервер проверяет то же самое заново, потому что запрос приходит не только
 * из этой формы (`docs/frontend.md` → «Обязательное поле — свойство поля»). Два числа,
 * написанные по обе стороны отдельно, расходятся на первой же правке, и расходятся молча:
 * форма продолжает пускать то, что сервер уже не принимает.
 */

/**
 * Какие типы принимаются и с каким расширением ложатся на том.
 *
 * Расширение берётся из этой таблицы, а не из имени присланного файла: имя приходит
 * от клиента, и `.jpg.php` в нём — ровно тот случай, ради которого имя файла с той стороны
 * не используется нигде.
 */
export const PHOTO_EXTENSION_BY_TYPE: Readonly<Record<string, string>> = {
  'image/jpeg': 'jpg',
  'image/png': 'png',
  'image/webp': 'webp',
};

/**
 * Потолок размера фото. Пять мегабайт — вдвое больше самой тяжёлой картинки старого
 * каталога; смысл потолка не в экономии диска, а в том, чтобы случайный RAW с телефона
 * не уехал на том целиком.
 */
export const MAX_PHOTO_BYTES = 5 * 1024 * 1024;

/** То же число мегабайтами — для подписи под полем и для текста отказа. */
export const MAX_PHOTO_MB = MAX_PHOTO_BYTES / (1024 * 1024);

/**
 * Значение атрибута `accept` для поля выбора файла.
 *
 * Собрано из той же таблицы типов, а не выписано строкой: новый принимаемый формат должен
 * появляться в диалоге выбора вместе с тем, как его начал принимать сервер.
 */
export const PHOTO_ACCEPT = Object.keys(PHOTO_EXTENSION_BY_TYPE).join(',');
