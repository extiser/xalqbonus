import type { EmployeeRole } from '../server/generated/prisma/enums';

/**
 * Кому какой раздел открыт.
 *
 * Список один на обе стороны: решает по нему сервер, а разметка по нему же прячет пункты,
 * которые человеку откажут. Два списка — серверный и клиентский — расходятся на первой же
 * правке, и расходятся тихо: пункт остаётся в шапке, а по нажатию приходит 403.
 */

/** Все роли сотрудников. Раздел, открытый всем, перечисляет их, а не обходится пустотой. */
export const ALL_EMPLOYEE_ROLES: readonly EmployeeRole[] = ['owner', 'admin', 'senior_manager', 'manager'];

/**
 * Экран наблюдаемости синхронизации и его ручки — только владельцу и админу.
 *
 * Менеджеру и старшему менеджеру он не нужен и ничего ему не говорит: там отметки окон, счётчики прогонов
 * и нерешённое пропущенное — материал разбора «работает ли синхронизация», а не работы
 * в офисе (issue #102).
 */
export const SYNC_ROLES: readonly EmployeeRole[] = ['owner', 'admin'];

/**
 * Офисы, каталог и остатки — владельцу, админу и старшему менеджеру.
 *
 * Менеджеру эти разделы закрыты не по недоверию, а по составу работы: он стоит в офисе
 * с телефоном и выдаёт заказы, а цены, закупочная стоимость и приход — работа того, кто
 * отвечает за каталог парка. Оформление прихода в этот же список входит намеренно: цифра
 * прихода — основание остатка, и править её должен тот же, кто отвечает за товар (issue #120).
 *
 * Старший менеджер и есть тот, кто отвечает за каталог: ради этой работы роль заведена
 * (issue #291, docs/decisions.md → «Старший менеджер; правка баллов и выдача наград руками —
 * не менеджеру»).
 */
export const CATALOG_ROLES: readonly EmployeeRole[] = ['owner', 'admin', 'senior_manager'];

/**
 * Отчёты — экран и выгрузка в Excel — владельцу, админу и старшему менеджеру (issue #308).
 *
 * Отчёты — это деньги и все офисы сразу, менеджеру у стойки они не нужны (решение Руслана
 * 30-09-2026). Своим списком, а не `CATALOG_ROLES`: состав сегодня совпадает, но это разные
 * права, и расходиться им позволено каждому по своей причине.
 */
export const REPORT_ROLES: readonly EmployeeRole[] = ['owner', 'admin', 'senior_manager'];

/**
 * Заказы офиса — выдача по коду и отмена — всем ролям: это и есть работа менеджера у стойки
 * (issue #122). Выдача наград на той же стойке открыта тем же списком (issue #172).
 *
 * В каком именно офисе человек работает, решает не этот список, а `ANY_OFFICE_ROLES` ниже:
 * роль открывает раздел, офис — заказы в нём.
 */
export const ORDER_ROLES: readonly EmployeeRole[] = ALL_EMPLOYEE_ROLES;

/**
 * Роли, которым открыт любой офис парка.
 *
 * Остальные работают только в офисах, к которым привязаны через `employee_offices`. Правило
 * одно на Mini App и веб и решается сервером (`server/services/offices/employeeOffices.ts`):
 * менеджер, набравший в адресе чужой офис, получает `role_not_allowed`, а не его заказы.
 *
 * Старший менеджер — здесь же, как админ: он ведёт офисы и остатки всего парка (issue #291).
 */
export const ANY_OFFICE_ROLES: readonly EmployeeRole[] = ['owner', 'admin', 'senior_manager'];

/**
 * Экран сотрудников и его ручки — учётки, приглашения, выключение, сброс пароля, смена роли —
 * владельцу и админу (issue #132, #291).
 *
 * Этот список открывает раздел, а над какой учёткой можно действовать, решает правило
 * «роль строго ниже своей» (`server/services/employees/roles.ts`). Оно же не даёт власти
 * над учётками ролям не из этого списка: старший менеджер старше менеджера рангом,
 * но не приглашает и не выключает никого.
 */
export const STAFF_ROLES: readonly EmployeeRole[] = ['owner', 'admin'];

/**
 * Рассылки — экран и все ручки, от черновика до остановки, — владельцу и админу (issue #136).
 *
 * Менеджеру и старшему менеджеру раздел закрыт: рассылка уходит всему парку разом, и отозвать отправленное
 * нельзя. Это работа того, кто говорит от имени парка, а не того, кто стоит у стойки.
 */
export const MAILING_ROLES: readonly EmployeeRole[] = ['owner', 'admin'];

/**
 * Сегменты водителей — экран и все ручки — владельцу и админу (issue #165).
 *
 * Менеджеру и старшему менеджеру раздел закрыт: срез парка — не работа у стойки, и следом за срезом идёт
 * рассылка, которую он и так не видит.
 */
export const SEGMENT_ROLES: readonly EmployeeRole[] = ['owner', 'admin'];

/**
 * Акции — экран и все ручки, от черновика до окна половины Б, — владельцу и админу (issue #166).
 *
 * Менеджеру и старшему менеджеру раздел закрыт: запуск акции необратим и трогает всю волну разом, а состав
 * после запуска не пересчитывается ничем.
 */
export const CAMPAIGN_ROLES: readonly EmployeeRole[] = ['owner', 'admin'];

/**
 * Дашборд метрик — экран и ручки — владельцу и админу (issue #371).
 *
 * Менеджеру и старшему менеджеру дашборд закрыт: это цифры всего парка — поездки, водители,
 * дальше деньги, — материал решений владельца, а не работы у стойки. Своим списком, а не
 * `SYNC_ROLES`: состав сегодня совпадает, но это разные права.
 */
export const METRICS_ROLES: readonly EmployeeRole[] = ['owner', 'admin'];

/**
 * Промо-метки — экран, ссылки, QR и все ручки — владельцу и админу (issue #380).
 *
 * Менеджеру и старшему менеджеру раздел закрыт: метка — это то, что парк печатает и раздаёт
 * от своего имени, а воронка по ней — цифры привлечения всего парка, материал решений владельца.
 * Своим списком, а не `METRICS_ROLES`: состав сегодня совпадает, но это разные права.
 */
export const PROMO_ROLES: readonly EmployeeRole[] = ['owner', 'admin'];

/**
 * Ручное начисление и списание баллов водителю — владельцу, админу и старшему менеджеру
 * (issue #131, #291).
 *
 * Менеджеру правка закрыта решением Руслана 29-09-2026. Открыта она ему была 14-09-2026
 * с доводом, что закрытая правка уйдёт в переписку операторов, а защитой служит след. Оба
 * довода отпали: выдача баллов через переписку запрещена парком, а след, который никто
 * не читает, не защищает — правку знакомому водителю никто не заметит. Защита теперь ролью:
 * правит руками тот, кто за это отвечает. Водитель, пришедший разбираться с баллами, идёт
 * к старшему менеджеру (docs/decisions.md → «Старший менеджер; правка баллов и выдача наград
 * руками — не менеджеру»).
 *
 * След остаётся: заметка обязательна, автор и его роль видны у строки истории. Список один
 * на обе двери (docs/decisions.md → «Доступ определяется ролью, а не дверью»).
 */
export const POINTS_ADJUST_ROLES: readonly EmployeeRole[] = ['owner', 'admin', 'senior_manager'];

/**
 * Ручная выдача награды одному водителю и раздел «Награды» — тем же списком, что ручная правка
 * баллов (issue #172, #291).
 *
 * Менеджеру закрыто по той же причине: награда со склада, выданная руками «под шумок», —
 * та же правка баллов, только товаром, и след её так же никто не читает (решение Руслана
 * 29-09-2026). У менеджера остаётся выдача по коду — заказов и наград, которые водитель
 * получил сам (`ORDER_ROLES`): это не ручная выдача, а вручение уже полученного.
 */
export const REWARD_GRANT_ROLES: readonly EmployeeRole[] = POINTS_ADJUST_ROLES;

/**
 * Раздача подарка сегменту (issue #219) — владельцу и админу, тем же списком, что сегменты.
 *
 * Сам раздел «Награды» открыт `REWARD_GRANT_ROLES`, и одному водителю подарок вручает
 * и старший менеджер. Сегменту — нет: раздача на тысячи человек — это решение того, кто говорит
 * от имени парка, и выбрать сегмент старшему менеджеру всё равно не из чего — раздел сегментов
 * ему закрыт.
 */
export const GIFT_SEGMENT_ROLES: readonly EmployeeRole[] = SEGMENT_ROLES;

/**
 * Кто правит демо-сущность — товар, офис, рассылку, сегмент, акцию, демо-сотрудника
 * (issue #212). Только владелец: демо — витрина программы, которую показывает он, и правка
 * чужими руками ломает показ. Остальные роли демо видят с пометкой «ДЕМО».
 *
 * Действия над демо-водителем — баллы, награда, подарок ему и демо-сегменту — правкой демо
 * не считаются: демо-водитель — тренажёр, на нём учат менеджеров и админов, и открыт он
 * тем же ролям, что живой (решение Руслана 26-09-2026).
 *
 * Решает сервер (`requireDemoEditor`); разметка по тому же правилу прячет кнопки правки
 * и поле «Демо» в формах заведения.
 */
export const DEMO_EDITOR_ROLES: readonly EmployeeRole[] = ['owner'];

/** Вправе ли роль править сущность с этим признаком. Живую — всякий, кого пустил раздел. */
export const canEditDemo = (role: EmployeeRole, isDemo: boolean): boolean =>
  !isDemo || DEMO_EDITOR_ROLES.includes(role);
