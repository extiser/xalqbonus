/**
 * Экранирование для `parse_mode: HTML`.
 *
 * Лежит в `shared/`, потому что зовут его по обе стороны: бот подставляет в разметку имя
 * водителя из чужой системы, рассылка — текст, набранный сотрудником, а форма рассылки
 * собирает то же сообщение, что уйдёт в Telegram. Угловая скобка в любой из этих строк
 * иначе ломает сообщение целиком, и водитель не получает ничего.
 */
export const escapeHtml = (value: string): string =>
  value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
