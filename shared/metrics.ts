export type MetricDefinition = {
  /** Название метрики — заголовок подсказки. */
  title: string;
  /** Что это значит, простым языком. Абзацы — через пустую строку. */
  text: string;
  /** Как считается; нет — подсказка из равных частей, без черты. */
  how?: string;
};

/** Подстановки в тексты подсказок: «8 недель», «3+ недели», «30». */
export type MetricPlaceholder =
  | 'leadersPercent'
  | 'normWeeks'
  | 'belowNormPercent'
  | 'streakWeeks'
  | 'streakPlus'
  | 'newcomerDays'
  | 'newcomerDaysAfter'
  | 'newcomerTrips'
  | 'driverValueFrom'
  | 'driverValueTo'
  | 'winbackOverYearRides';

export type MetricValues = Readonly<Partial<Record<MetricPlaceholder, string>>>;

/** Текст с подставленными значениями; неизвестная подстановка остаётся как есть. */
export const fillMetricText = (text: string, values: MetricValues | undefined): string =>
  text.replace(/\{(\w+)\}/g, (whole, name: string) => values?.[name as MetricPlaceholder] ?? whole);

