import type { WebLanguage } from './denials';

/**
 * Отказы стойки выдачи — заказа и награды: у каждого свой код, а текст к нему — здесь.
 * Награды живут в том же словаре, а не своём: поле кода у стойки одно, и «код не найден»
 * у неё один на оба (issue #172).
 *
 * Словарь отдельный от `shared/denials.ts` намеренно. Там — отказы двери: кто вошёл и что
 * ему открыто. Здесь — отказы предмета разговора: заказа с таким кодом нет, заказ уже выдан.
 * Собрать их в одном месте значило бы собрать там половину логики приложения
 * (docs/decisions.md → «Граница словаря — дверь»). Устройство при этом то же самое: код
 * решает, что делает экран, текст берётся по коду, язык — язык админки.
 *
 * Относительным путём, а не через `#shared`: так же подключается водительский контракт
 * из словаря бота, и у двух соседних файлов `shared/` не должно быть двух способов.
 */

export type OrderDenialCode =
  /**
   * По коду среди висящих заказов и ждущих наград этого офиса не нашлось ничего. Чужой офис —
   * тот же ответ.
   */
  | 'desk_code_not_found'
  /** Заказа с таким идентификатором нет вовсе. */
  | 'order_not_found'
  /** Заказ уже выдан — исход двойного нажатия «Выдать» и гонки двух сотрудников. */
  | 'order_already_issued'
  /** Заказ уже отменён: водителем, сотрудником или просрочкой. */
  | 'order_already_cancelled'
  /** Награды с таким идентификатором нет, или она не выдаётся на стойке. */
  | 'reward_not_found'
  /** Награда уже выдана — исход двойного нажатия и гонки двух сотрудников. */
  | 'reward_already_issued'
  /** Награда сгорела: срок вышел, товар вернулся на полку. */
  | 'reward_already_expired';

/** Что лежит в `data` отказавшей ручки заказа. */
export type OrderDenialPayload = { code: OrderDenialCode };

/**
 * Текст на каждый отказ. Полнота проверяется типом: код без текста не собирается.
 *
 * «Код не найден» не говорит, есть ли такой код в другом офисе, — и не должен: код
 * не подтверждает существование заказа тому, кто стоит не там (`issueOrder`).
 */
const ORDER_DENIAL_TEXTS: Readonly<Record<OrderDenialCode, Readonly<Record<WebLanguage, string>>>> = {
  desk_code_not_found: {
    ru: 'Код не найден. Проверьте цифры с водителем: код действует, пока заказ или награда ждёт выдачи в этом офисе.',
  },
  order_not_found: {
    ru: 'Такого заказа нет. Обновите список заказов.',
  },
  order_already_issued: {
    ru: 'Заказ уже выдан.',
  },
  order_already_cancelled: {
    ru: 'Заказ уже отменён, баллы водителю вернулись.',
  },
  reward_not_found: {
    ru: 'Такой награды нет. Найдите её по коду заново.',
  },
  reward_already_issued: {
    ru: 'Награда уже выдана.',
  },
  reward_already_expired: {
    ru: 'Награда сгорела: срок вышел, товар вернулся на полку.',
  },
};

export const orderDenialText = (code: OrderDenialCode, language: WebLanguage): string =>
  ORDER_DENIAL_TEXTS[code][language];
