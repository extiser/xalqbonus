/**
 * Номер телефона: одно правило приведения на весь проект и его показ человеку.
 *
 * Телефон — не личность, а канал связи (docs/drivers.md), но именно он единственный
 * подтверждён Telegram, и вся автопривязка строится на нём одном. Поэтому регистрация,
 * синхронизация и экран обязаны понимать номер **одинаково**: реестр наполняет прогон
 * профилей, ищет в нём регистрация, а экран показывает водителю тот же номер, по которому
 * искали. Разойдись эти места — привязка перестанет находить того, кого прогон только что
 * записал, или экран покажет номер не в том виде, в каком его знает база.
 *
 * Лежит в `shared/`, потому что читают его обе стороны: сервер приводит номер к форме
 * реестра, клиент показывает телефон офиса.
 */

/**
 * Канонический вид: плюс, код страны, девять цифр.
 *
 * Единственная форма, по которой идёт автопривязка. 446 номеров реестра ей не отвечают
 * и остаются с пустым `phone_e164` — иностранные, короткие, битые: угадывать за них
 * нельзя, цена ошибки в том, что номер сойдётся с чужим.
 */
const E164_UZBEKISTAN = /^\+998\d{9}$/;

/** Всё, чем номер разбивают при вводе и при выгрузке из чужой системы. */
const SEPARATORS = /[\s\-()]/g;

/**
 * Приводит номер к каноническому виду `+998XXXXXXXXX` или отвечает `null`.
 *
 * Что принимается: канонический номер как есть, он же без плюса — так его отдаёт Telegram
 * в `contact.phone_number`, — и любой из двух с пробелами, дефисами или скобками.
 *
 * Что **не** принимается и почему: девять цифр без кода страны. Дописать `+998` за
 * водителя значит решить за него, что номер узбекский, — а номер, к которому дописали
 * чужой код, найдёт в реестре постороннего человека вместе с его баллами. Пусто здесь
 * честнее догадки: исход «в офис» стоит похода, ошибка привязки стоит чужого баланса.
 */
export const normalizePhoneE164 = (rawPhone: string): string | null => {
  const digitsOnly = rawPhone.trim().replace(SEPARATORS, '');
  const withPlus = digitsOnly.startsWith('+') ? digitsOnly : `+${digitsOnly}`;

  return E164_UZBEKISTAN.test(withPlus) ? withPlus : null;
};

/** Номер для экрана: как показать и что положить в буфер обмена. */
export type FormattedPhone = {
  /** «+998 90 123-45-67». */
  display: string;
  /** «+998901234567» — без пробелов: так его вставляют в поиск админки. */
  copy: string;
};

/**
 * Номер в виде, в котором его читают глазами: `+998 90 123-45-67`.
 *
 * Номер, который к канонической форме не приводится, показывается как пришёл — и в буфер
 * уходит так же. Переписать его в «правильный» вид значило бы показать менеджеру номер,
 * которого водитель не присылал, а искать попытку в журнале будут по присланному.
 */
export const formatPhone = (rawPhone: string): FormattedPhone => {
  const canonical = normalizePhoneE164(rawPhone);

  if (canonical === null) {
    return { display: rawPhone, copy: rawPhone };
  }

  const operator = canonical.slice(4, 6);
  const head = canonical.slice(6, 9);
  const middle = canonical.slice(9, 11);
  const tail = canonical.slice(11, 13);

  return { display: `+998 ${operator} ${head}-${middle}-${tail}`, copy: canonical };
};
